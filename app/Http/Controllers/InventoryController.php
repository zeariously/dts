    /**
     * Build one category's latest Purchase Request validation.
     */
    private function buildPurchaseRequestValidation(
        string $category
    ): array {
        $category =
            $this->normalizePurchaseRequestCategory(
                $category
            );

        $empty =
            $this->emptyPurchaseRequestValidation(
                $category
            );

        $directory =
            storage_path(
                'app/inventory/purchase-request/'
                . $category
            );

        if (!is_dir($directory)) {
            return $empty;
        }

        $metadataPath =
            $directory
            . DIRECTORY_SEPARATOR
            . 'current.json';

        if (!is_file($metadataPath)) {
            return $empty;
        }

        $metadata =
            json_decode(
                (string) file_get_contents(
                    $metadataPath
                ),
                true
            );

        if (!is_array($metadata)) {
            return [
                ...$empty,
                'error' =>
                    'The saved Purchase Request metadata could not be read.',
            ];
        }

        $needsYear =
            in_array(
                $category,
                ['supplies', 'ict'],
                true
            );

        $year =
            $needsYear
                ? (int) (
                    $metadata['inventory_year']
                    ?? 0
                )
                : null;

        if (
            $needsYear
            && $year < 2026
        ) {
            return [
                ...$empty,
                'error' =>
                    'The saved Purchase Request Inventory Year is invalid.',
            ];
        }

        $referencePath = null;
        $extension = null;

        foreach (
            ['xlsx', 'csv']
            as $candidateExtension
        ) {
            $candidate =
                $directory
                . DIRECTORY_SEPARATOR
                . 'current.'
                . $candidateExtension;

            if (is_file($candidate)) {
                $referencePath =
                    $candidate;

                $extension =
                    $candidateExtension;

                break;
            }
        }

        if (!$referencePath) {
            return [
                ...$empty,
                'error' =>
                    'The saved Purchase Request file could not be found.',
            ];
        }

        try {
            $prRows =
                $this->parsePurchaseRequestSpreadsheet(
                    $referencePath,
                    (string) $extension,
                    $category
                );

            $inventoryItems =
                $this->purchaseRequestInventoryItems(
                    $category,
                    $year
                );

            $validation =
                match ($category) {
                    'supplies' =>
                        $this->validateSuppliesPurchaseRequestRows(
                            $prRows,
                            $inventoryItems,
                            (int) $year
                        ),

                    'ict' =>
                        $this->validateIctPurchaseRequestRows(
                            $prRows,
                            $inventoryItems,
                            (int) $year
                        ),

                    default =>
                        $this->validateOtherPurchaseRequestRows(
                            $prRows,
                            $inventoryItems,
                            $category
                        ),
                };

            return [
                'has_file' => true,

                'file' => [
                    'original_name' =>
                        $metadata['original_name']
                        ?? basename(
                            $referencePath
                        ),

                    'uploaded_at' =>
                        $metadata['uploaded_at']
                        ?? date(
                            DATE_ATOM,
                            filemtime(
                                $referencePath
                            )
                        ),

                    'uploaded_by' =>
                        $metadata['uploaded_by']
                        ?? 'Unknown',

                    'row_count' =>
                        $metadata['row_count']
                        ?? count(
                            $prRows
                        ),
                ],

                'context' => [
                    'validation_category' =>
                        $category,

                    'category_label' =>
                        $this->purchaseRequestCategoryLabel(
                            $category
                        ),

                    'inventory_year' =>
                        $year,
                ],

                'summary' =>
                    $validation['summary'],

                'rows' =>
                    $validation['rows'],

                'error' => null,
            ];
        } catch (\Throwable $exception) {
            Log::error(
                'Purchase Request validation failed.',
                [
                    'category' =>
                        $category,

                    'message' =>
                        $exception->getMessage(),
                ]
            );

            return [
                ...$empty,

                'has_file' => true,

                'file' => [
                    'original_name' =>
                        $metadata['original_name']
                        ?? basename(
                            $referencePath
                        ),

                    'uploaded_at' =>
                        $metadata['uploaded_at']
                        ?? null,

                    'uploaded_by' =>
                        $metadata['uploaded_by']
                        ?? 'Unknown',

                    'row_count' =>
                        $metadata['row_count']
                        ?? null,
                ],

                'context' => [
                    'validation_category' =>
                        $category,

                    'category_label' =>
                        $this->purchaseRequestCategoryLabel(
                            $category
                        ),

                    'inventory_year' =>
                        $year,
                ],

                'error' =>
                    'The saved Purchase Request could not be validated: '
                    . $exception->getMessage(),
            ];
        }
    }

    private function purchaseRequestInventoryItems(
        string $category,
        ?int $year
    ) {
        $query =
            InventoryItem::query();

        if ($category === 'supplies') {
            $query
                ->whereRaw(
                    "LOWER(TRIM(category)) = 'supplies'"
                )
                ->where(
                    'inventory_year',
                    $year
                );
        } elseif ($category === 'ict') {
            $query
                ->whereRaw(
                    "LOWER(TRIM(category)) = 'ict'"
                )
                ->where(
                    'inventory_year',
                    $year
                );
        } elseif ($category === 'furniture_fixtures') {
            $query->where(
                function ($builder) {
                    $builder
                        ->whereRaw(
                            "LOWER(TRIM(category)) = 'furniture'"
                        )
                        ->orWhereRaw(
                            "LOWER(TRIM(category)) = 'fixtures'"
                        );
                }
            );
        } else {
            $query->whereRaw(
                'LOWER(TRIM(category)) = ?',
                [$category]
            );
        }

        return $query
            ->orderBy('item')
            ->get();
    }

    /**
     * Supplies: Item + Unit + exact PR Quarter + Quantity.
     * Quantity uses only quarter_stock[PR quarter].added.
     */
    private function validateSuppliesPurchaseRequestRows(
        array $prRows,
        $inventoryItems,
        int $year
    ): array {
        $rows = [];

        $summary = [
            'total' => 0,
            'match' => 0,
            'not_match' => 0,
            'not_found' => 0,
        ];

        foreach ($prRows as $index => $prRow) {
            if (!is_array($prRow)) {
                continue;
            }

            $itemName = trim(
                (string) ($prRow['item'] ?? '')
            );

            $unit = strtoupper(
                trim(
                    (string) ($prRow['unit'] ?? '')
                )
            );

            $prQuarterRaw = trim(
                (string) ($prRow['quarter'] ?? '')
            );

            $quarter =
                $this->normalizePurchaseRequestQuarter(
                    $prQuarterRaw
                );

            $quantityRaw = trim(
                (string) ($prRow['quantity'] ?? '')
            );

            $quantity = is_numeric($quantityRaw)
                ? (float) $quantityRaw
                : null;

            $baseRow = [
                'id' => 'pr:' . ($index + 1),
                'item' => $itemName,
                'unit' => $unit,
                'quarter' =>
                    $quarter
                    ?? strtoupper($prQuarterRaw),
                'quantity' => $quantity,
                'inventory_year' => $year,
                'status' => 'not_found',
                'notes' => '',
            ];

            $itemMatches =
                $inventoryItems
                    ->filter(
                        fn ($inventoryItem) =>
                            $this->normalizePurchaseRequestItemText(
                                $inventoryItem->item
                            )
                            ===
                            $this->normalizePurchaseRequestItemText(
                                $itemName
                            )
                    )
                    ->values();

            if ($itemMatches->isEmpty()) {
                $rows[] = [
                    ...$baseRow,
                    'status' => 'not_found',
                    'notes' =>
                        'Item was not found in the '
                        . $year
                        . ' Supplies inventory.',
                ];

                $summary['not_found']++;
                $summary['total']++;
                continue;
            }

            $sameUnit =
                $itemMatches
                    ->filter(
                        fn ($inventoryItem) =>
                            strtoupper(
                                trim(
                                    (string) $inventoryItem->unit
                                )
                            )
                            === $unit
                    )
                    ->values();

            $inventoryItem =
                $sameUnit->first()
                ?? $itemMatches->first();

            $systemUnit = strtoupper(
                trim(
                    (string) $inventoryItem->unit
                )
            );

            $quarterList =
                $this->normalizedQuarterList(
                    $inventoryItem->quarters
                    ?? []
                );

            $quarterStock =
                $this->normalizedStoredQuarterStock(
                    $inventoryItem->quarter_stock
                );

            $notes = [];

            if ($systemUnit !== $unit) {
                $notes[] =
                    'Unit does not match. PR: '
                    . ($unit !== '' ? $unit : 'Blank')
                    . ', System: '
                    . ($systemUnit !== '' ? $systemUnit : 'Blank')
                    . '.';
            }

            $quarterMatches = false;
            $quarterEntry = null;

            if ($quarter === null) {
                $notes[] =
                    'Quarter is invalid. PR: '
                    . (
                        $prQuarterRaw !== ''
                            ? $prQuarterRaw
                            : 'Blank'
                    )
                    . '. Use Q1, Q2, Q3, or Q4.';
            } else {
                $quarterEntry =
                    $quarterStock[$quarter]
                    ?? null;

                $quarterMatches =
                    in_array(
                        $quarter,
                        $quarterList,
                        true
                    )
                    && is_array($quarterEntry)
                    && $this->quarterStockEntryHasActivity(
                        $quarterEntry
                    );

                if (!$quarterMatches) {
                    $notes[] =
                        'No '
                        . strtoupper($quarter)
                        . ' record found in the Inventory for this item.';
                }
            }

            if ($quantity === null) {
                $notes[] =
                    'Quantity is missing or invalid in the Purchase Request.';
            } elseif ($quarterMatches) {
                $systemQuantity = max(
                    0,
                    (float) (
                        $quarterEntry['added']
                        ?? 0
                    )
                );

                if (
                    abs(
                        $quantity
                        - $systemQuantity
                    )
                    >= 0.000001
                ) {
                    $notes[] =
                        'Quantity does not match. PR: '
                        . $this->formatPurchaseRequestNumber(
                            $quantity
                        )
                        . ', System: '
                        . $this->formatPurchaseRequestNumber(
                            $systemQuantity
                        )
                        . '.';
                }
            }

            if (empty($notes)) {
                $rows[] = [
                    ...$baseRow,
                    'status' => 'match',
                    'notes' =>
                        'All Purchase Request details match the Inventory record.',
                ];

                $summary['match']++;
            } else {
                $rows[] = [
                    ...$baseRow,
                    'status' => 'not_match',
                    'notes' => implode(' ', $notes),
                ];

                $summary['not_match']++;
            }

            $summary['total']++;
        }

        return [
            'summary' => $summary,
            'rows' => $rows,
        ];
    }

