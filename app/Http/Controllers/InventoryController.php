    /**
     * Stable Purchase Request quantity to compare against.
     *
     * Physical ICT / Furniture:
     * - Count remains the total asset count even after assignment.
     *
     * ICT MONTH/YEAR / Emergency Kits / Token and Giveaways:
     * - Releases reduce currently_available, so add tracked_released back
     *   to reconstruct the current system-entered total quantity.
     */
    private function purchaseRequestSystemQuantity(
        InventoryItem $item,
        string $category
    ): float {
        $category =
            $this->normalizePurchaseRequestCategory(
                $category
            );

        $unit =
            strtoupper(
                trim(
                    (string) $item->unit
                )
            );

        $assets =
            is_array($item->ict_assets)
                ? array_values(
                    array_filter(
                        $item->ict_assets,
                        'is_array'
                    )
                )
                : [];

        if ($category === 'ict') {
            if (
                !in_array(
                    $unit,
                    ['MONTH', 'YEAR'],
                    true
                )
            ) {
                return (float) (
                    !empty($assets)
                        ? count($assets)
                        : max(
                            0,
                            (int) (
                                $item->currently_available
                                ?? 0
                            )
                        )
                );
            }

            return (float) (
                max(
                    0,
                    (int) (
                        $item->currently_available
                        ?? 0
                    )
                )
                + max(
                    0,
                    (int) (
                        $item->tracked_released
                        ?? 0
                    )
                )
            );
        }

        if ($category === 'furniture_fixtures') {
            return (float) (
                !empty($assets)
                    ? count($assets)
                    : max(
                        0,
                        (int) (
                            $item->currently_available
                            ?? 0
                        )
                    )
            );
        }

        return (float) (
            max(
                0,
                (int) (
                    $item->currently_available
                    ?? 0
                )
            )
            + max(
                0,
                (int) (
                    $item->tracked_released
                    ?? 0
                )
            )
        );
    }

    private function normalizePurchaseRequestQuarter(
        mixed $value
    ): ?string {
        $value = strtoupper(
            trim((string) $value)
        );

        $value = preg_replace(
            '/[^A-Z0-9]+/',
            '',
            $value
        );

        return match ($value) {
            'Q1',
            'QUARTER1',
            '1STQUARTER',
            'FIRSTQUARTER',
            '1' => 'q1',

            'Q2',
            'QUARTER2',
            '2NDQUARTER',
            'SECONDQUARTER',
            '2' => 'q2',

            'Q3',
            'QUARTER3',
            '3RDQUARTER',
            'THIRDQUARTER',
            '3' => 'q3',

            'Q4',
            'QUARTER4',
            '4THQUARTER',
            'FOURTHQUARTER',
            '4' => 'q4',

            default => null,
        };
    }

    private function formatPurchaseRequestNumber(
        float|int $value
    ): string {
        $number = (float) $value;

        if (
            abs(
                $number
                - round($number)
            )
            < 0.000001
        ) {
            return number_format(
                $number,
                0,
                '.',
                ','
            );
        }

        return rtrim(
            rtrim(
                number_format(
                    $number,
                    4,
                    '.',
                    ','
                ),
                '0'
            ),
            '.'
        );
    }

