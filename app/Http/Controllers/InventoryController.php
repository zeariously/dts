    /**
     * Normalize item text for Purchase Request matching.
     */
    private function normalizePurchaseRequestItemText(
        mixed $value
    ): string {
        $value =
            mb_strtolower(
                trim(
                    (string) $value
                )
            );

        $value =
            preg_replace(
                '/[^\pL\pN]+/u',
