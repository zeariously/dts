                '/\s+/u',
                ' ',
                (string) $value
            )
        );
    }

    /**
     * Parse a category-specific Purchase Request spreadsheet.
     *
     * Supplies: Item | Unit | Quarter | Quantity
     * ICT: Item | Unit | Quantity
     * Other Items: Item | Quantity
     */
    private function parsePurchaseRequestSpreadsheet(
        string $path,
        string $extension,
        string $category
    ): array {
        $category =
            $this->normalizePurchaseRequestCategory(
                $category
            );

        $extension =
            strtolower(
                $extension
            );

        $rawRows =
            $extension === 'xlsx'
                ? $this->readInventoryXlsx(
                    $path
                )
                : $this->readInventoryCsv(
                    $path
                );

        if (empty($rawRows)) {
            return [];
        }

        $requiredFields =
            match ($category) {
                'supplies' =>
                    [
                        'item',
                        'unit',
                        'quarter',
                        'quantity',
                    ],

                'ict' =>
                    [
                        'item',
                        'unit',
                        'quantity',
                    ],

                default =>
                    [
                        'item',
                        'quantity',
                    ],
            };

        $headerIndex = null;
        $headers = [];

        foreach (
            array_slice(
                $rawRows,
                0,
                30,
                true
            )
            as $index => $row
        ) {
            $candidateHeaders = [];

            foreach (
                $row
                as $columnIndex => $header
            ) {
                $normalized =
                    $this->normalizePurchaseRequestHeader(
                        $header
                    );

                if ($normalized !== null) {
                    $candidateHeaders[
                        $columnIndex
                    ] = $normalized;
                }
            }

            $fields =
                array_values(
                    $candidateHeaders
                );

            $hasAllRequired = true;

            foreach (
                $requiredFields
                as $requiredField
            ) {
                if (!in_array(
                    $requiredField,
                    $fields,
                    true
                )) {
                    $hasAllRequired = false;
                    break;
                }
            }

            if ($hasAllRequired) {
                $headerIndex = $index;
                $headers = $candidateHeaders;
                break;
            }
        }

        if ($headerIndex === null) {
            $displayFields =
                array_map(
                    fn ($field) =>
                        match ($field) {
                            'item' => 'Item',
                            'unit' => 'Unit',
                            'quarter' => 'Quarter',
                            'quantity' => 'Quantity',
                            default => ucfirst($field),
                        },
                    $requiredFields
                );

            throw new \RuntimeException(
                'No valid Purchase Request header row was found. Required columns: '
                . implode(
                    ', ',
                    $displayFields
                )
                . '.'
            );
        }

        $rows = [];

        foreach (
            array_slice(
                $rawRows,
                $headerIndex + 1
            )
            as $rawRow
        ) {
            $row = [];

            foreach (
                $headers
                as $columnIndex => $field
            ) {
                $row[$field] =
                    trim(
                        (string) (
                            $rawRow[
                                $columnIndex
                            ]
                            ?? ''
                        )
                    );
            }

            $hasValue = false;

            foreach (
                $requiredFields
                as $field
            ) {
                if (
                    trim(
                        (string) (
                            $row[$field]
                            ?? ''
                        )
                    ) !== ''
                ) {
                    $hasValue = true;
                    break;
                }
            }

            if (!$hasValue) {
                continue;
            }

            $rows[] = $row;
        }

        return $rows;
    }

    private function normalizePurchaseRequestHeader(
