    private function readInventoryCsv(
        string $path
    ): array {
        $handle =
            fopen(
                $path,
                'rb'
            );

        if (!$handle) {
            throw new \RuntimeException(
                'Unable to open CSV file.'
            );
        }

        $firstLine =
            fgets($handle);

        rewind($handle);

        $delimiter = ',';

        if ($firstLine !== false) {
            $scores = [
                ',' =>
                    substr_count(
                        $firstLine,
                        ','
                    ),

                ';' =>
                    substr_count(
                        $firstLine,
                        ';'
                    ),

                "\t" =>
                    substr_count(
                        $firstLine,
                        "\t"
                    ),
            ];

            arsort($scores);

            $delimiter =
                (string) array_key_first(
                    $scores
                );
        }

        $rows = [];

        while (
            (
                $row = fgetcsv(
                    $handle,
                    0,
                    $delimiter
                )
            ) !== false
        ) {
            $rows[] =
                array_map(
                    fn ($value) =>
                        $this->stripSpreadsheetBom(
                            $value
                        ),
                    $row
                );
        }

        fclose($handle);

        return $rows;
    }

    private function stripSpreadsheetBom(
        mixed $value
    ): string {
        return preg_replace(
            '/^\xEF\xBB\xBF/',
            '',
            (string) $value
        );
    }

    private function readInventoryXlsx(
        string $path
    ): array {
        if (
            !class_exists(
                \ZipArchive::class
            )
        ) {
            throw new \RuntimeException(
                'PHP ZIP extension is not enabled. Enable/install php-zip before uploading XLSX files.'
            );
        }

        if (
            !function_exists(
                'simplexml_load_string'
            )
        ) {
            throw new \RuntimeException(
                'PHP SimpleXML extension is not enabled. Enable/install php-xml before uploading XLSX files.'
            );
        }

        $zip =
            new \ZipArchive();

        $openResult =
            $zip->open($path);

        if ($openResult !== true) {
            throw new \RuntimeException(
                'The XLSX file could not be opened as an Excel workbook.'
            );
        }

        try {
            
            $sharedStrings = [];

            $sharedXml =
                $zip->getFromName(
                    'xl/sharedStrings.xml'
                );

            if ($sharedXml !== false) {
                libxml_use_internal_errors(true);

                $xml =
                    simplexml_load_string(
                        $sharedXml
                    );

                if ($xml === false) {
                    throw new \RuntimeException(
                        'The XLSX shared strings XML is invalid.'
                    );
                }

                $stringItems =
                    $xml->xpath(
                        '//*[local-name()="si"]'
                    ) ?: [];

                foreach (
                    $stringItems
                    as $stringItem
                ) {
                    $textParts =
                        $stringItem->xpath(
                            './/*[local-name()="t"]'
                        ) ?: [];

                    $text = '';

                    foreach (
                        $textParts
                        as $textPart
                    ) {
                        $text .=
                            (string) $textPart;
                    }

                    $sharedStrings[] =
                        $text;
                }

                libxml_clear_errors();
            }

            
            $sheetPath =
                'xl/worksheets/sheet1.xml';

            $sheetXml =
                $zip->getFromName(
                    $sheetPath
                );

            if ($sheetXml === false) {
                $sheetCandidates = [];

                for (
                    $index = 0;
                    $index < $zip->numFiles;
                    $index++
                ) {
                    $stat =
                        $zip->statIndex(
                            $index
                        );

                    $name =
                        (string) (
                            $stat['name']
                            ?? ''
                        );

                    if (
                        preg_match(
                            '#^xl/worksheets/sheet\d+\.xml$#',
                            $name
                        )
                    ) {
                        $sheetCandidates[] =
                            $name;
                    }
                }

                sort(
                    $sheetCandidates,
                    SORT_NATURAL
                );

                $sheetPath =
                    $sheetCandidates[0]
                    ?? null;

                if (!$sheetPath) {
                    throw new \RuntimeException(
                        'The XLSX file does not contain a readable worksheet.'
                    );
                }

                $sheetXml =
                    $zip->getFromName(
                        $sheetPath
                    );
            }

            if ($sheetXml === false) {
                throw new \RuntimeException(
                    'The XLSX worksheet could not be read.'
                );
            }

            libxml_use_internal_errors(true);

            $sheet =
                simplexml_load_string(
                    $sheetXml
                );

            if ($sheet === false) {
                throw new \RuntimeException(
                    'The XLSX worksheet XML is invalid.'
                );
            }

            $rowNodes =
                $sheet->xpath(
                    '//*[local-name()="sheetData"]/*[local-name()="row"]'
                ) ?: [];

            if (empty($rowNodes)) {
                throw new \RuntimeException(
                    'The first worksheet does not contain readable rows.'
                );
            }

            $rows = [];

            foreach (
                $rowNodes
                as $row
            ) {
                $values = [];

                $cells =
                    $row->xpath(
                        './*[local-name()="c"]'
                    ) ?: [];

                foreach (
                    $cells
                    as $cell
                ) {
                    $attributes =
                        $cell->attributes();

                    $reference =
                        trim(
                            (string) (
                                $attributes['r']
                                ?? ''
                            )
                        );

                    preg_match(
                        '/^([A-Z]+)/i',
                        $reference,
                        $matches
                    );

                    $column =
                        $this->xlsxColumnIndex(
                            strtoupper(
                                $matches[1]
                                ?? 'A'
                            )
                        );

                    $type =
                        trim(
                            (string) (
                                $attributes['t']
                                ?? ''
                            )
                        );

                    $value = '';

                    if ($type === 'inlineStr') {
                        $textParts =
                            $cell->xpath(
                                './/*[local-name()="is"]//*[local-name()="t"]'
                            ) ?: [];

                        foreach (
                            $textParts
                            as $textPart
                        ) {
                            $value .=
                                (string) $textPart;
                        }
                    } else {
                        $valueNodes =
                            $cell->xpath(
                                './*[local-name()="v"]'
                            ) ?: [];

                        $raw =
                            isset(
                                $valueNodes[0]
                            )
                                ? (string) $valueNodes[0]
                                : '';

                        if (
                            $type === 's'
                            && $raw !== ''
                        ) {
                            $value =
                                $sharedStrings[
                                    (int) $raw
                                ]
                                ?? '';
                        } else {
                            $value =
                                $raw;
                        }
                    }

                    $values[$column] =
                        $this->stripSpreadsheetBom(
                            $value
                        );
                }

                if (empty($values)) {
                    $rows[] = [];
                    continue;
                }

                $max =
                    max(
                        array_keys(
                            $values
                        )
                    );

                $dense =
                    array_fill(
                        0,
                        $max + 1,
                        ''
                    );

                foreach (
                    $values
                    as $column => $value
                ) {
                    $dense[$column] =
                        $value;
                }

                $rows[] =
                    $dense;
            }

            libxml_clear_errors();

            return $rows;
        } finally {
            $zip->close();
        }
    }

    private function xlsxColumnIndex(
        string $letters
    ): int {
        $letters =
            strtoupper(
                $letters
            );

        $index = 0;

        foreach (
            str_split($letters)
            as $letter
        ) {
            $index =
                ($index * 26)
                + (
                    ord($letter)
                    - 64
                );
        }

        return max(
            0,
            $index - 1
        );
    }

   
    /**
     * Personnel available for Memorandum Receipt (MR) assignment.
     *
     * The DTS lu_personnel table in older installations does not have an
     * employment-status field. We therefore:
     * 1. scope to Special Projects Division when lu_office can identify it;
     * 2. filter to Permanent automatically when a supported status column
     *    exists in lu_personnel;
     * 3. otherwise return the SPD personnel list so MR assignment still works.
     */
    private function inventoryMrPersonnel(): array
    {
        if (!Schema::hasTable('lu_personnel')) {
            return [];
        }

        $query =
            DB::table('lu_personnel as p')
                ->whereNotNull('p.name')
                ->whereRaw(
                    "TRIM(p.name) != ''"
                )
                ->whereRaw(
                    "TRIM(p.name) != '-'"
                );

        /*
         * Prefer personnel assigned to the Special Projects Division.
         */
        if (Schema::hasTable('lu_office')) {
            $spdOfficeIds =
                DB::table('lu_office')
                    ->where(function ($officeQuery) {
                        if (
                            Schema::hasColumn(
                                'lu_office',
                                'abbrev'
                            )
                        ) {
                            $officeQuery
                                ->whereRaw(
                                    "LOWER(TRIM(COALESCE(abbrev, ''))) = ?",
                                    ['spd']
                                );
                        } else {
                            $officeQuery
                                ->whereRaw('1 = 0');
                        }

                        if (
                            Schema::hasColumn(
                                'lu_office',
                                'officename'
                            )
                        ) {
                            $officeQuery
                                ->orWhereRaw(
                                    "LOWER(TRIM(COALESCE(officename, ''))) LIKE ?",
                                    ['%special project%']
                                );
                        }
                    })
                    ->pluck('ID')
                    ->map(
                        fn ($id) => (int) $id
                    )
                    ->filter()
                    ->values()
                    ->all();

            if (
                !empty($spdOfficeIds)
                && Schema::hasColumn(
                    'lu_personnel',
                    'IDoffice'
                )
            ) {
                $query->whereIn(
                    'p.IDoffice',
                    $spdOfficeIds
                );
            }
        }

        /*
         * Newer personnel tables may already identify Permanent employees.
         * Use the first supported status column found.
         */
        foreach (
            [
                'employment_status',
                'employment_type',
                'appointment_status',
                'appointment_type',
            ]
            as $statusColumn
        ) {
            if (
                Schema::hasColumn(
                    'lu_personnel',
                    $statusColumn
                )
            ) {
                $query->whereRaw(
                    "LOWER(TRIM(COALESCE(p.{$statusColumn}, ''))) = ?",
                    ['permanent']
                );

                break;
            }
        }

        return $query
            ->orderBy('p.name')
            ->select([
                'p.ID as id',
                'p.name',
            ])
            ->get()
            ->map(
                fn ($person) => [
                    'id' =>
                        (int) $person->id,
                    'name' =>
                        trim(
                            (string) $person->name
                        ),
                ]
            )
            ->values()
            ->all();
    }


    private function canManageInventory(
        $user
    ): bool {
        if (!$user) {
            return false;
        }

        $role =
            $user->rights
            ?? $user->role
            ?? $user->role_number
            ?? null;

        return trim(
            (string) $role
        ) === '3';
    }

   
    private function authorizeInventoryManagement(
        Request $request
    ): void {
        abort_unless(
            $this->canManageInventory(
                $request->user()
            ),
            403,
            'You have view-only access to the Inventory module.'
        );
    }

    public function destroy(
        Request $request,
        InventoryItem $inventoryItem
    ) {
        $this->authorizeInventoryManagement(
            $request
        );

        
        $inventoryItem->histories()->delete();
        $inventoryItem->delete();

        return back()->with(
            'success',
            'Inventory item deleted successfully.'
        );
    }
