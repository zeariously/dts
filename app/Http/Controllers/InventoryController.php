    private function comparisonDisplayValue(
        mixed $value,
        string $field = ''
    ): string {
        $value =
            trim(
                (string) $value
            );

        if (
            $field === 'current_user'
            && $value === ''
        ) {
            return 'Unassigned';
        }

        return $value === ''
            ? '—'
            : $value;
    }

    private function normalizeComparisonValue(
        mixed $value,
        string $field = ''
    ): string {
        $value =
            trim(
                (string) $value
            );

        if (
            in_array(
                $field,
                [
                    'available',
                    'inventory_year',
                ],
                true
            )
            && $value !== ''
            && is_numeric($value)
        ) {
            return (string) (
                $value + 0
            );
        }

        return $this->normalizeComparisonText(
            $value
        );
    }

    private function normalizeComparisonText(
        mixed $value
    ): string {
        $value =
            preg_replace(
                '/\s+/u',
                ' ',
                trim(
                    (string) $value
                )
            );

        return mb_strtolower(
            (string) $value
        );
    }

    private function normalizeComparisonCategory(
        mixed $value
    ): string {
        $value =
            $this->normalizeComparisonText(
                $value
            );

        if ($value === '') {
            return '';
        }

        if (
            str_contains(
                $value,
                'supply'
            )
        ) {
            return 'supplies';
        }

        if (
            $value === 'ict'
            || str_contains(
                $value,
                'information and communication'
            )
        ) {
            return 'ict';
        }

        if (
            str_contains(
                $value,
                'furniture'
            )
            || str_contains(
                $value,
                'fixture'
            )
        ) {
            return 'furniture_fixtures';
        }

        if (
            str_contains(
                $value,
                'emergency'
            )
        ) {
            return 'emergency_kits';
        }

        if (
            str_contains(
                $value,
                'token'
            )
            || str_contains(
                $value,
                'giveaway'
            )
        ) {
            return 'token_giveaways';
        }

        return str_replace(
            [' ', '-', '/'],
            '_',
            $value
        );
    }

    /**
     * XLSX/CSV reader kept inside Inventory so no new Composer package
     * is required for the reconciliation prototype.
     */
    private function parseReconciliationSpreadsheet(
        string $path,
        string $extension
    ): array {
        $extension =
            strtolower(
                $extension
            );

        $rawRows =
            $extension === 'xlsx'
                ? $this->readInventoryXlsx(
                    $path
                )
                : $this->readInventoryCsv(
                    $path
                );

        if (empty($rawRows)) {
            return [];
        }

        $headerIndex = null;
        $headers = [];

        /*
         * Do not assume the first non-empty row is the header.
         * Real inventory sheets often have a title/agency name above it.
         * Scan the first 25 rows and choose the first row containing at
         * least one supported identity column (Item Name or Property No.).
         */
        foreach (
            array_slice(
                $rawRows,
                0,
                25,
                true
            )
            as $index => $row
        ) {
            $candidateHeaders = [];

            foreach (
                $row
                as $columnIndex => $header
            ) {
                $normalized =
                    $this->normalizeInventorySpreadsheetHeader(
                        $header
                    );

                if ($normalized !== null) {
                    $candidateHeaders[
                        $columnIndex
                    ] = $normalized;
                }
            }

            $candidateValues =
                array_values(
                    $candidateHeaders
                );

            if (
                in_array(
                    'item',
                    $candidateValues,
                    true
                )
                || in_array(
                    'property_number',
                    $candidateValues,
                    true
                )
            ) {
                $headerIndex =
                    $index;

                $headers =
                    $candidateHeaders;

                break;
            }
        }

        if (
            $headerIndex === null
            || empty($headers)
        ) {
            throw new \RuntimeException(
                'No supported header row was found. Include at least Item Name or Property Number in the spreadsheet headers.'
            );
        }

        $rows = [];

        foreach (
            array_slice(
                $rawRows,
                $headerIndex + 1
            )
            as $rawRow
        ) {
            $row = [
                '_present' =>
                    array_values(
                        array_unique(
                            array_values(
                                $headers
                            )
                        )
                    ),
            ];

            $hasData = false;

            foreach (
                $headers
                as $columnIndex => $field
            ) {
                $value =
                    trim(
                        (string) (
                            $rawRow[
                                $columnIndex
                            ]
                            ?? ''
                        )
                    );

                if ($value !== '') {
                    $hasData = true;
                }

                $row[$field] =
                    $field === 'category'
                        ? $this->normalizeComparisonCategory(
                            $value
                        )
                        : $value;
            }

            if (!$hasData) {
                continue;
            }

           
            if (
                trim(
                    (string) (
                        $row['item']
                        ?? ''
                    )
                ) === ''
                && trim(
                    (string) (
                        $row[
                            'property_number'
                        ]
                        ?? ''
                    )
                ) === ''
            ) {
                continue;
            }

            $rows[] =
                $row;
        }

        return $rows;
    }

    private function normalizeInventorySpreadsheetHeader(
        mixed $header
    ): ?string {
        $header =
            $this->normalizeComparisonText(
                $header
            );

        $header =
            str_replace(
                [
                    '_',
                    '-',
                    '/',
                    '\\',
                    '(',
                    ')',
                    '.',
                    '#',
                ],
                ' ',
                $header
            );

        $header =
            preg_replace(
                '/\s+/u',
                ' ',
                trim($header)
            );

        $aliases = [
            'category' => [
                'category',
                'type',
                'inventory category',
            ],

            'item' => [
                'item',
                'item name',
                'inventory item',
                'article',
                'particulars',
            ],

            'unit' => [
                'unit',
                'uom',
                'unit of measure',
                'unit measure',
            ],

            'inventory_year' => [
                'inventory year',
                'year',
            ],

            'available' => [
                'available',
                'currently available',
                'currently available in spd',
                'current',
                'remaining',
                'balance',
                'count',
                'quantity',
                'qty',
                'duration',
                'count duration',
            ],

            'description' => [
                'description',
                'asset description',
            ],

            'property_number' => [
                'property number',
                'property no',
                'property num',
                'property',
                'property tag',
            ],

            'current_user' => [
