class InventoryController extends Controller
{
    /**
     * Inventory page.
     */
    public function index(Request $request)
    {
        return Inertia::render('DTS/Inventory', [
            'canManageInventory' =>
                $this->canManageInventory(
                    $request->user()
                ),

            'inventoryItems' => InventoryItem::query()
                ->orderByRaw("
                    CASE
                        WHEN LOWER(TRIM(category)) = 'supplies' THEN 1
                        WHEN LOWER(TRIM(category)) = 'ict' THEN 2
                        WHEN LOWER(TRIM(category)) IN ('furniture', 'fixtures') THEN 3
                        WHEN LOWER(TRIM(category)) = 'emergency_kits' THEN 4
                        WHEN LOWER(TRIM(category)) = 'token_giveaways' THEN 5
                        ELSE 6
                    END
                ")
                ->orderBy('item')
                ->get(),

            /*
             * Read-only reconciliation data per inventory category.
             * Each category keeps its own reference spreadsheet.
             */
            'reconciliations' =>
                $this->buildInventoryReconciliations(),

            /*
             * MR dropdown personnel.
             * Prefer SPD personnel and, when the personnel table has an
             * employment/appointment status column, restrict to Permanent.
             */
            'mrPersonnel' =>
                $this->inventoryMrPersonnel(),
        ]);
    }

    /**
     * Add a new Supplies, ICT, or Other Items record.
     *
     * SUPPLIES
     * - Fixed Value is optional.
     * - Currently Available is required.
     * - If Fixed Value exists (> 0):
     *      Quantity Released = Fixed - Current (generated by MySQL)
     * - If Fixed Value is missing / 0:
     *      tracked_released starts at 0 and future releases accumulate there.
     *
     * ICT
     * - No Quarter. Normal items: Item, Unit, Count, Inventory Year, Remarks.
     * - Subscription: Unit = MONTH or YEAR and currently_available stores duration.
     * - Release and History are supported for ICT changes.
     *
     * OTHER ITEMS
     * - Furniture/Fixtures / Emergency Kits / Token and Giveaways:
     *   Item, Count (stored in currently_available), Location, Remarks.
     * - All Other Items use Count, Release, and History.
     */
    public function store(Request $request)
    {
        $this->authorizeInventoryManagement(
            $request
        );

        $validated = $request->validate([
            'category' => 'required|in:supplies,ict,furniture,fixtures,emergency_kits,token_giveaways',
            'item' => 'required|string|max:255',
            'description' => 'nullable|string|max:1000',
            'location' =>
                'required_if:category,furniture,fixtures,emergency_kits,token_giveaways|nullable|string|max:255',
            'unit' =>
                'required_if:category,supplies,ict|nullable|string|max:50',
            'inventory_year' =>
                'required_if:category,supplies,ict|nullable|integer|min:2026|max:2100',
            'fixed_value' => 'nullable|integer|min:0',
            'currently_available' =>
                'required_if:category,ict,furniture,fixtures,emergency_kits,token_giveaways|nullable|integer|min:0',
            'ict_assets' => 'nullable|array',
            'ict_assets.*' => 'array',
            'ict_assets.*.description' => 'nullable|string|max:255',
            'ict_assets.*.accessories' => 'nullable|string|max:500',
            'ict_assets.*.property_number' => 'nullable|string|max:100',
            'ict_assets.*.current_user' => 'nullable|string|max:255',
            'ict_assets.*.date_acquired' => 'nullable|date_format:Y-m-d',
            'ict_assets.*.life_span_ended' => 'nullable|date_format:Y-m-d',
            'ict_assets.*.status' => 'nullable|in:working,returned,for_return',
            'ict_assets.*.mr_personnel_id' => 'nullable|integer|exists:lu_personnel,ID',
            'ict_assets.*.mr' => 'nullable|string|max:255',
            'quarters' =>
                'required_if:category,supplies|nullable|array|min:1',
            'quarters.*' => 'in:q1,q2,q3,q4',
            'quarter_stock' =>
                'required_if:category,supplies|nullable|array',
            'quarter_stock.*' =>
                'array',
            'quarter_stock.*.current' =>
                'required|integer|min:0',
            'quarter_stock.*.remarks' =>
                'nullable|string|max:1000',
            'remarks' => 'nullable|string',
        ]);

        $validated['category'] =
            strtolower(trim($validated['category']));

        /*
         * Description belongs to individual physical assets in ict_assets.
         */
        $validated['description'] = null;

        $otherCategories = [
            'furniture',
            'fixtures',
            'emergency_kits',
            'token_giveaways',
        ];

        $propertyTrackedOtherCategories = [
            'furniture',
            'fixtures',
        ];

        $isOtherItem =
            in_array(
                $validated['category'],
                $otherCategories,
                true
            );

        if ($isOtherItem) {
            /*
             * Compatibility-only internal values.
             * These are NEVER shown or filtered in the Other Items UI.
             * The existing schema requires Unit / Year / Quarter values.
             */
            $validated['location'] =
                trim((string) $validated['location']);

            $validated['currently_available'] =
                (int) $validated['currently_available'];

            $validated['unit'] = 'N/A';
            $validated['inventory_year'] =
                max(2026, (int) now()->year);
            $validated['quarters'] = [
                'q1',
                'q2',
                'q3',
                'q4',
            ];

            $validated['fixed_value'] = null;
            $validated['quarter_stock'] = null;

            $validated['ict_assets'] =
                in_array(
                    $validated['category'],
                    $propertyTrackedOtherCategories,
                    true
                )
                    ? $this->normalizedIctAssets(
                        $validated['ict_assets'] ?? [],
                        (int) $validated['currently_available'],
                        true,
                        true
                    )
                    : null;
        } else {
            $validated['location'] = null;

            $validated['unit'] =
                strtoupper(trim($validated['unit']));

            if ($validated['category'] === 'supplies') {
                $quarters =
                    $this->normalizedQuarterList(
                        $validated['quarters'] ?? []
                    );

                $quarterStock =
                    $this->buildQuarterStock(
                        $quarters,
                        $validated['quarter_stock'] ?? [],
                        null
                    );

                $validated['quarters'] =
                    $quarters;

                $validated['quarter_stock'] =
                    $quarterStock;
                $validated['ict_assets'] = null;

                $validated['currently_available'] =
                    $this->quarterStockCurrentTotal(
                        $quarterStock
                    );
            } else {
                /*
                 * ICT keeps a real Item Name, just like Supplies.
                 * Unit of Measure remains separate so MONTH/YEAR
                 * subscriptions can still use duration tracking.
                 */
                $validated['quarters'] = [];
                $validated['quarter_stock'] = null;
                $validated['fixed_value'] = null;
                $validated['currently_available'] =
                    (int) $validated['currently_available'];

                $validated['ict_assets'] =
                    in_array(
                        $validated['unit'],
                        ['MONTH', 'YEAR'],
                        true
                    )
                        ? null
                        : $this->normalizedIctAssets(
                            $validated['ict_assets'] ?? [],
                            (int) $validated['currently_available'],
                            true,
                            true
                        );
            }
        }

        /*
         * Never send total_released or tracked_released from the form.
         * - total_released is generated by MySQL.
         * - tracked_released starts at DB default 0.
         */
        InventoryItem::create($validated);

        return back()->with(
            'success',
            'Inventory item added successfully.'
        );
    }

    /**
     * Update / release an inventory item.
     */
    public function update(
        Request $request,
        InventoryItem $inventoryItem
    ) {
        $this->authorizeInventoryManagement(
            $request
        );

        $validated = $request->validate([
            'release_quantity' =>
                'sometimes|required|integer|min:1',

            'release_destination' =>
                'sometimes|nullable|string|max:255',

            'release_property_number' =>
                'sometimes|nullable|string|max:100',

            'release_mr_personnel_id' =>
                'sometimes|nullable|integer|exists:lu_personnel,ID',

            'release_quarter' =>
                'sometimes|nullable|in:q1,q2,q3,q4',

            'category' =>
                'sometimes|required|in:supplies,ict,furniture,fixtures,emergency_kits,token_giveaways',

            'item' =>
                'sometimes|required|string|max:255',

            'description' =>
                'sometimes|nullable|string|max:1000',

            'location' =>
                'sometimes|nullable|string|max:255',

            'unit' =>
                'sometimes|required|string|max:50',

            'inventory_year' =>
                'sometimes|required|integer|min:2026|max:2100',

            'fixed_value' =>
                'sometimes|nullable|integer|min:0',

            'currently_available' =>
                'sometimes|nullable|integer|min:0',

            'add_other_count' =>
                'sometimes|nullable|integer|min:1',

            'new_other_asset' =>
                'sometimes|nullable|array',

            'new_other_asset.description' =>
                'nullable|string|max:255',

            'new_other_asset.property_number' =>
                'nullable|string|max:100',

            'new_other_asset.current_user' =>
                'nullable|string|max:255',

            /*
             * Simple ICT item editing:
             * - add_ict_count adds new blank Property Detail rows.
             * - asset_index + asset edits one accordion row only.
             */
            'new_ict_asset' =>
                'sometimes|nullable|array',

            'new_ict_asset.description' =>
                'nullable|string|max:255',

            'new_ict_asset.accessories' =>
                'nullable|string|max:500',

            'new_ict_asset.property_number' =>
                'nullable|string|max:100',

            'new_ict_asset.current_user' =>
                'nullable|string|max:255',

            'new_ict_asset.date_acquired' =>
                'nullable|date_format:Y-m-d',

            'new_ict_asset.life_span_ended' =>
                'nullable|date_format:Y-m-d',

            'new_ict_asset.status' =>
                'nullable|in:working,returned,for_return',

            'new_ict_asset.mr_personnel_id' =>
                'nullable|integer|exists:lu_personnel,ID',

            'new_ict_asset.mr' =>
                'nullable|string|max:255',

            'asset_index' =>
                'sometimes|nullable|integer|min:0',

            'asset' =>
                'sometimes|nullable|array',

            'asset.description' =>
                'nullable|string|max:255',

            'asset.accessories' =>
                'nullable|string|max:500',

            'asset.property_number' =>
                'nullable|string|max:100',

            'asset.current_user' =>
                'nullable|string|max:255',

            'asset.date_acquired' =>
                'nullable|date_format:Y-m-d',

            'asset.life_span_ended' =>
                'nullable|date_format:Y-m-d',

            'asset.status' =>
                'nullable|in:working,returned,for_return',

            'asset.mr_personnel_id' =>
                'nullable|integer|exists:lu_personnel,ID',

            'asset.mr' =>
                'nullable|string|max:255',

            'ict_assets' => 'sometimes|nullable|array',
            'ict_assets.*' => 'array',
            'ict_assets.*.description' => 'nullable|string|max:255',
            'ict_assets.*.accessories' => 'nullable|string|max:500',
            'ict_assets.*.property_number' => 'nullable|string|max:100',
            'ict_assets.*.current_user' => 'nullable|string|max:255',
            'ict_assets.*.date_acquired' => 'nullable|date_format:Y-m-d',
            'ict_assets.*.life_span_ended' => 'nullable|date_format:Y-m-d',
            'ict_assets.*.status' => 'nullable|in:working,returned,for_return',
            'ict_assets.*.mr_personnel_id' => 'nullable|integer|exists:lu_personnel,ID',
            'ict_assets.*.mr' => 'nullable|string|max:255',

            'quarters' =>
                'sometimes|nullable|array',

            'quarters.*' =>
                'in:q1,q2,q3,q4',

            'quarter_stock' =>
                'sometimes|nullable|array',

            'quarter_stock.*' =>
                'array',

            'quarter_stock.*.current' =>
                'required|integer|min:0',

            'quarter_stock.*.remarks' =>
                'nullable|string|max:1000',

            'remarks' =>
                'sometimes|nullable|string',
        ]);

        $user = $request->user();

        $userId = $user?->getKey();

        $userName =
            $user?->name
            ?? $user?->loginname
            ?? $user?->username
            ?? $user?->email
            ?? 'Unknown User';

        DB::transaction(function () use (
            $inventoryItem,
            $validated,
            $userId,
            $userName
        ) {
            /*
             * Lock the row so simultaneous releases cannot overdraw stock.
             */
            $item = InventoryItem::query()
                ->whereKey($inventoryItem->id)
                ->lockForUpdate()
                ->firstOrFail();

            /*
             * Full audit snapshot BEFORE any edit/release changes.
             * This lets History record Item Name, Unit, Year, Quarter(s),
             * Fixed Value, Currently Available, Remarks, etc.
             */
            $historyOldData =
                $this->inventoryHistorySnapshot($item);

            $category =
                strtolower(trim((string) $item->category));

            $oldCurrent =
                $item->currently_available !== null
                    ? (int) $item->currently_available
                    : null;

            $oldTrackedReleased =
                (int) ($item->tracked_released ?? 0);

            $oldHasFixedBaseline =
                $item->fixed_value !== null
                && (int) $item->fixed_value > 0;

            $oldDisplayedReleased =
                $oldHasFixedBaseline
                    && $oldCurrent !== null
                        ? max(
                            0,
                            (int) $item->fixed_value
                            - $oldCurrent
                        )
                        : $oldTrackedReleased;

            $oldRemarks =
                $item->remarks;

            $isRelease =
                array_key_exists(
                    'release_quantity',
                    $validated
                );

            $isIctAssetEdit =
                !$isRelease
                && array_key_exists(
                    'asset_index',
                    $validated
                );

            $hasNewIctAsset =
                !$isRelease
                && array_key_exists(
                    'new_ict_asset',
                    $validated
                )
                && is_array(
                    $validated['new_ict_asset']
                    ?? null
                );

            $hasAddOtherCount =
                !$isRelease
                && array_key_exists(
                    'add_other_count',
                    $validated
                )
                && (int) (
                    $validated['add_other_count']
                    ?? 0
                ) > 0;

            $hasNewOtherAsset =
                !$isRelease
                && array_key_exists(
                    'new_other_asset',
                    $validated
                )
                && is_array(
                    $validated['new_other_asset']
                    ?? null
                );

            /*
             * A remark entered in the Release modal belongs to
             * that release transaction. It must not become the
             * permanent item remark or reappear next time.
             */
            $releaseRemarks =
                $isRelease
                    ? trim(
                        (string) (
                            $validated['remarks']
                            ?? ''
                        )
                    )
                    : '';

            $releaseDestination =
                $isRelease
                    ? trim(
                        (string) (
                            $validated['release_destination']
                            ?? ''
                        )
                    )
                    : '';

            $releasePropertyNumber =
                $isRelease
                    ? trim(
                        (string) (
                            $validated['release_property_number']
                            ?? ''
                        )
                    )
                    : '';

            $releaseMrPersonnelId =
                $isRelease
                    ? (int) (
                        $validated['release_mr_personnel_id']
                        ?? 0
                    )
                    : 0;

            if (!$isRelease) {
                $targetCategory = strtolower(
                    trim((string) ($validated['category'] ?? $item->category))
                );

                $targetItemName = trim(
                    (string) ($validated['item'] ?? $item->item)
                );

                $otherCategories = [
                    'furniture',
                    'fixtures',
                    'emergency_kits',
                    'token_giveaways',
                ];

                $targetIsOther =
                    in_array(
                        $targetCategory,
                        $otherCategories,
                        true
                    );

                $targetLocation = trim(
                    (string) (
                        $validated['location']
                        ?? $item->location
                        ?? ''
                    )
                );

                $targetUnit = strtoupper(
                    trim((string) ($validated['unit'] ?? $item->unit))
                );

                $targetYear = (int) (
                    $validated['inventory_year']
                    ?? $item->inventory_year
                    ?? 2026
                );

                if (
                    $targetIsOther
                    && $targetLocation === ''
                ) {
                    throw ValidationException::withMessages([
                        'location' =>
                            'Location is required for Other Items.',
                    ]);
                }


                $targetRequiresCount =
                    in_array(
                        $targetCategory,
                        [
                            'furniture',
                            'fixtures',
                            'emergency_kits',
                            'token_giveaways',
                        ],
                        true
                    );

                $targetItemCount =
                    $validated['currently_available']
                    ?? $item->currently_available
                    ?? null;

                if (
                    $targetRequiresCount
                    && (
                        $targetItemCount === null
                        || (int) $targetItemCount < 0
                    )
                ) {
                    throw ValidationException::withMessages([
                        'currently_available' =>
                            'Count is required for this category.',
                    ]);
                }

                $duplicateQuery = InventoryItem::query()
                    ->where('id', '!=', $item->id)
                    ->whereRaw(
                        'LOWER(TRIM(category)) = ?',
                        [$targetCategory]
                    )
                    ->whereRaw(
                        'LOWER(TRIM(item)) = ?',
                        [strtolower($targetItemName)]
                    );

                if ($targetIsOther) {
                    $duplicateQuery->whereRaw(
                        'LOWER(TRIM(COALESCE(location, ""))) = ?',
                        [strtolower($targetLocation)]
                    );
                } else {
                    $duplicateQuery
                        ->whereRaw(
                            'UPPER(TRIM(unit)) = ?',
                            [$targetUnit]
                        )
                        ->where(
                            'inventory_year',
                            $targetYear
                        );
                }

                if ($duplicateQuery->exists()) {
                    throw ValidationException::withMessages([
                        'item' =>
                            $targetIsOther
                                ? 'This item already exists in the same location.'
                                : "This item and unit already exist for {$targetYear}.",
                    ]);
                }
            }
            /**
             * ========================================================
             * RELEASE QUANTITY / DURATION
             * ========================================================
             *
             * Supplies + ICT are quarter-aware.
             * Releases automatically use the latest assigned quarter.
             * Previous quarter balances remain historical snapshots.
             * Other counted items keep their existing global Count flow.
             */
            if (
                array_key_exists(
                    'release_quantity',
                    $validated
                )
            ) {
                $releaseableCategories = [
                    'supplies',
                    'ict',
                    'furniture',
                    'fixtures',
                    'emergency_kits',
                    'token_giveaways',
                ];

                if (
                    !in_array(
                        $category,
                        $releaseableCategories,
                        true
                    )
                ) {
                    throw ValidationException::withMessages([
                        'release_quantity' =>
                            'This inventory category does not use quantity release tracking.',
                    ]);
                }

                /*
                 * Supplies only need quantity + optional remarks.
                 * ICT and counted Other Items still require destination.
                 */
                if (
                    $category !== 'supplies'
                    && $releaseDestination === ''
                ) {
                    throw ValidationException::withMessages([
                        'release_destination' =>
                            'Released To / Destination is required.',
                    ]);
                }

                $releaseQuantity =
                    (int) $validated['release_quantity'];

                $usesQuarterStock =
                    $category === 'supplies';

                if ($usesQuarterStock) {
                    $assignedQuarters =
                        $this->normalizedQuarterList(
                            is_array($item->quarters)
                                ? $item->quarters
                                : []
                        );

                    $storedQuarterStock =
                        $this->normalizedStoredQuarterStock(
                            $item->quarter_stock
                        );

                    /*
                     * No quarter selector in the UI.
                     * Release always uses the latest ACTIVE quarter.
                     * Zero future quarters in All Quarters are ignored.
                     */
                    $releaseQuarter =
                        $this->latestActiveQuarter(
                            $storedQuarterStock,
                            $assignedQuarters
                        )
                        ?? '';

                    if ($releaseQuarter === '') {
                        throw ValidationException::withMessages([
                            'release_quantity' =>
                                'No active quarter is available for this item.',
                        ]);
                    }

                    /*
                     * Legacy single-quarter item:
                     * safely initialize its quarter from the old global balance.
                     *
                     * Legacy multi-quarter item:
                     * cannot be split accurately, so force one-time Edit setup.
                     */
                    if (empty($storedQuarterStock)) {
                        if (
                            count($assignedQuarters) !== 1
                        ) {
                            throw ValidationException::withMessages([
                                'release_quarter' =>
                                    'Set the remaining quantity for each quarter in Edit before releasing this legacy multi-quarter item.',
                            ]);
                        }

                        $onlyQuarter =
                            $assignedQuarters[0];

                        $legacyCurrent =
                            $oldCurrent ?? 0;

                        $legacyReleased =
                            max(
                                0,
                                (int) $oldDisplayedReleased
                            );

                        $storedQuarterStock = [
                            $onlyQuarter => [
                                'opening' =>
                                    $legacyCurrent
                                    + $legacyReleased,
                                'current' =>
                                    $legacyCurrent,
                                'released' =>
                                    $legacyReleased,
                            ],
                        ];
                    }

                    $quarterEntry =
                        $storedQuarterStock[
                            $releaseQuarter
                        ]
                        ?? null;

                    if (!$quarterEntry) {
                        throw ValidationException::withMessages([
                            'release_quarter' =>
                                'Set the balance for this quarter in Edit before releasing.',
                        ]);
                    }

                    $quarterCurrent =
                        (int) (
                            $quarterEntry['current']
                            ?? 0
                        );

                    if (
                        $releaseQuantity
                        > $quarterCurrent
                    ) {
                        throw ValidationException::withMessages([
                            'release_quantity' =>
                                "Only {$quarterCurrent} available in "
                                . strtoupper($releaseQuarter)
                                . '.',
                        ]);
                    }

                    $quarterReleased =
                        (int) (
                            $quarterEntry['released']
                            ?? 0
                        );

                    $quarterEntry['current'] =
                        $quarterCurrent
                        - $releaseQuantity;

                    $quarterEntry['released'] =
                        $quarterReleased
                        + $releaseQuantity;

                    $quarterEntry['opening'] =
                        (int) (
                            $quarterEntry['opening']
                            ?? (
                                $quarterCurrent
                                + $quarterReleased
                            )
                        );

                    $storedQuarterStock[
                        $releaseQuarter
                    ] =
                        $quarterEntry;

                    $item->quarter_stock =
                        $storedQuarterStock;

                    $item->currently_available =
                        $this->quarterStockCurrentTotal(
                            $storedQuarterStock
                        );

                    $hasFixedBaseline =
                        $category === 'supplies'
                        && $item->fixed_value !== null
                        && (int) $item->fixed_value > 0;

                    if (!$hasFixedBaseline) {
                        $item->tracked_released =
                            $this->quarterStockReleasedTotal(
                                $storedQuarterStock
                            );
                    }
                } else {
                    $isPropertyTrackedAsset =
                        (
                            $category === 'ict'
                            && !in_array(
                                strtoupper(trim((string) $item->unit)),
                                ['MONTH', 'YEAR'],
                                true
                            )
                        )
                        || in_array(
                            $category,
                            ['furniture', 'fixtures'],
                            true
                        );

                    if ($isPropertyTrackedAsset) {
                        if ($releaseQuantity !== 1) {
                            throw ValidationException::withMessages([
                                'release_quantity' =>
                                    'Property-tracked items are released one Property Number at a time.',
                            ]);
                        }

                        if ($releasePropertyNumber === '') {
                            throw ValidationException::withMessages([
                                'release_property_number' =>
                                    'Select an available Property Number.',
                            ]);
                        }

                        $assets =
                            $this->normalizedIctAssetRowsForStorage(
                                $item->ict_assets ?? [],
                                (int) (
                                    $item->currently_available
                                    ?? 0
                                )
                            );

                        $matchedIndex = null;

                        foreach ($assets as $index => $asset) {
                            if (
                                mb_strtolower(trim((string) ($asset['property_number'] ?? '')))
                                === mb_strtolower($releasePropertyNumber)
                            ) {
                                $matchedIndex = $index;
                                break;
                            }
                        }

                        if ($matchedIndex === null) {
                            throw ValidationException::withMessages([
                                'release_property_number' =>
                                    'The selected Property Number does not belong to this item.',
                            ]);
                        }

                        if (
                            trim((string) ($assets[$matchedIndex]['current_user'] ?? '')) !== ''
                        ) {
                            throw ValidationException::withMessages([
                                'release_property_number' =>
                                    'The selected Property Number is no longer available.',
                            ]);
                        }

                        if (
                            $category === 'ict'
                            && $releaseMrPersonnelId <= 0
                        ) {
                            throw ValidationException::withMessages([
                                'release_mr_personnel_id' =>
                                    'Select the MR Holder.',
                            ]);
                        }

                        $assets[$matchedIndex]['current_user'] =
                            $releaseDestination;

                        if (
                            $category === 'ict'
                            && $releaseMrPersonnelId > 0
                        ) {
                            $mrName =
                                DB::table('lu_personnel')
                                    ->where(
                                        'ID',
                                        $releaseMrPersonnelId
                                    )
                                    ->value('name');

                            if (
                                !is_string($mrName)
                                || trim($mrName) === ''
                            ) {
                                throw ValidationException::withMessages([
                                    'release_mr_personnel_id' =>
                                        'The selected MR Holder is invalid.',
                                ]);
                            }

                            $assets[$matchedIndex]['mr_personnel_id'] =
                                $releaseMrPersonnelId;

                            $assets[$matchedIndex]['mr'] =
                                trim($mrName);
                        }

                        $item->ict_assets = $assets;

                        /*
                         * Count remains the total physical asset count.
                         * Available is derived from blank Current User rows.
                         */
                        $item->tracked_released =
                            $oldTrackedReleased + 1;
                    } else {
                        if ($oldCurrent === null) {
                            throw ValidationException::withMessages([
                                'release_quantity' =>
                                    'Available quantity is not configured for this item.',
                            ]);
                        }

                        if ($releaseQuantity > $oldCurrent) {
                            throw ValidationException::withMessages([
                                'release_quantity' =>
                                    "Only {$oldCurrent} available.",
                            ]);
                        }

                        $item->currently_available =
                            $oldCurrent - $releaseQuantity;

                        $item->tracked_released =
                            $oldTrackedReleased + $releaseQuantity;
                    }
                }
            }

            /**
             * ========================================================
             * INDIVIDUAL PROPERTY ROW EDIT
             * ========================================================
             *
             * Physical ICT and Furniture/Fixtures property rows are edited
             * one at a time from their accordion. Item-level Edit never
             * bulk-rewrites existing Furniture/Fixtures property rows.
             */
            if ($isIctAssetEdit) {
                $assetCategory =
                    strtolower(
                        trim(
                            (string) $item->category
                        )
                    );

                $assetUnit =
                    strtoupper(
                        trim(
                            (string) $item->unit
                        )
                    );

                $isPhysicalIct =
                    $assetCategory === 'ict'
                    && !in_array(
                        $assetUnit,
                        ['MONTH', 'YEAR'],
                        true
                    );

                $isOtherPropertyItem =
                    in_array(
                        $assetCategory,
                        ['furniture', 'fixtures'],
                        true
                    );

                if (
                    !$isPhysicalIct
                    && !$isOtherPropertyItem
                ) {
                    throw ValidationException::withMessages([
                        'asset_index' =>
                            'Property-row editing is available only for physical ICT or Furniture/Fixtures items.',
                    ]);
                }

                $assetCount =
                    max(
                        0,
                        (int) (
                            $item->currently_available
                            ?? 0
                        )
                    );

                $assetIndex =
                    (int) $validated['asset_index'];

                if (
                    $assetIndex < 0
                    || $assetIndex >= $assetCount
                ) {
                    throw ValidationException::withMessages([
                        'asset_index' =>
                            'The selected Property Detail row is invalid.',
                    ]);
                }

                $submittedAsset =
                    is_array(
                        $validated['asset']
                        ?? null
                    )
                        ? $validated['asset']
                        : [];

                $submittedNormalizedAsset =
                    $this->normalizedIctAssets(
                        [$submittedAsset],
                        1,
                        true,
                        true
                    )[0];

                $assets =
                    $this->normalizedIctAssetRowsForStorage(
                        $item->ict_assets ?? [],
                        $assetCount
                    );

                /*
                 * ICT replaces the complete property record because all ICT
                 * property fields are editable in the individual modal.
                 *
                 * Furniture/Fixtures only own Description, Property Number,
                 * and Current User here. Preserve any legacy/unrelated keys.
                 */
                if ($isPhysicalIct) {
                    $normalizedAsset =
                        $submittedNormalizedAsset;

                    if (
                        trim(
                            (string) (
                                $normalizedAsset['status']
                                ?? ''
                            )
                        ) === ''
                    ) {
                        throw ValidationException::withMessages([
                            'asset.status' =>
                                'Select Working or Returned.',
                        ]);
                    }
                } else {
                    $existingAsset =
                        is_array(
                            $assets[$assetIndex]
                            ?? null
                        )
                            ? $assets[$assetIndex]
                            : [];

                    $normalizedAsset =
                        array_merge(
                            $existingAsset,
                            [
                                'description' =>
                                    $submittedNormalizedAsset[
                                        'description'
                                    ],

                                'property_number' =>
                                    $submittedNormalizedAsset[
                                        'property_number'
                                    ],

                                'current_user' =>
                                    $submittedNormalizedAsset[
                                        'current_user'
                                    ],
                            ]
                        );
                }

                $newPropertyNumber =
                    mb_strtolower(
                        trim(
                            (string) (
                                $normalizedAsset[
                                    'property_number'
                                ]
                                ?? ''
                            )
                        )
                    );

                foreach (
                    $assets
                    as $index => $asset
                ) {
                    if ($index === $assetIndex) {
                        continue;
                    }

                    $existingPropertyNumber =
                        mb_strtolower(
                            trim(
                                (string) (
                                    $asset[
                                        'property_number'
                                    ]
                                    ?? ''
                                )
                            )
                        );

                    if (
                        $newPropertyNumber !== ''
                        && $existingPropertyNumber
                            === $newPropertyNumber
                    ) {
                        throw ValidationException::withMessages([
                            'asset.property_number' =>
                                'Property Number must be unique for this item.',
                        ]);
                    }
                }

                $assets[$assetIndex] =
                    $normalizedAsset;

                $item->ict_assets =
                    $assets;
            }

            if ($hasNewIctAsset) {
                $targetCategory =
                    strtolower(
                        trim(
                            (string) (
                                $validated['category']
                                ?? $item->category
                            )
                        )
                    );

                $targetUnit =
                    strtoupper(
                        trim(
                            (string) (
                                $validated['unit']
                                ?? $item->unit
                            )
                        )
                    );

                if (
                    $targetCategory !== 'ict'
                    || in_array(
                        $targetUnit,
                        ['MONTH', 'YEAR'],
                        true
                    )
                ) {
                    throw ValidationException::withMessages([
                        'new_ict_asset' =>
                            'New Property Details can be added only to physical ICT items.',
                    ]);
                }

                $submittedAsset =
                    $validated['new_ict_asset'];

                $normalizedAsset =
                    $this->normalizedIctAssets(
                        [$submittedAsset],
                        1,
                        true,
                        true
                    )[0];

                if (
                    trim(
                        (string) (
                            $normalizedAsset['status']
                            ?? ''
                        )
                    ) === ''
                ) {
                    throw ValidationException::withMessages([
                        'new_ict_asset.status' =>
                            'Select Working or Returned.',
                    ]);
                }

                $oldCount =
                    max(
                        0,
                        (int) (
                            $item->currently_available
                            ?? 0
                        )
                    );

                $assets =
                    $this->normalizedIctAssetRowsForStorage(
                        $item->ict_assets ?? [],
                        $oldCount
                    );

                $newPropertyNumber =
                    mb_strtolower(
                        trim(
                            (string) (
                                $normalizedAsset[
                                    'property_number'
                                ]
                                ?? ''
                            )
                        )
                    );

                foreach ($assets as $asset) {
                    $existingPropertyNumber =
                        mb_strtolower(
                            trim(
                                (string) (
                                    $asset[
                                        'property_number'
                                    ]
                                    ?? ''
                                )
                            )
                        );

                    if (
                        $newPropertyNumber !== ''
                        && $existingPropertyNumber
                            === $newPropertyNumber
                    ) {
                        throw ValidationException::withMessages([
                            'new_ict_asset.property_number' =>
                                'Property Number must be unique for this ICT item.',
                        ]);
                    }
                }

                $assets[] =
                    $normalizedAsset;

                $item->currently_available =
                    $oldCount + 1;

                $item->ict_assets =
                    $assets;
            }

            /**
             * ========================================================
             * OPTIONAL GENERAL UPDATES
             * ========================================================
             */
            if (array_key_exists('category', $validated)) {
                $item->category =
                    strtolower(trim($validated['category']));
            }

            if (array_key_exists('item', $validated)) {
                $item->item =
                    trim($validated['item']);
            }

            if (
                !$isRelease
                && array_key_exists(
                    'description',
                    $validated
                )
            ) {
                $item->description =
                    $validated['description'] !== null
                        ? (
                            trim(
                                (string) $validated['description']
                            )
                            ?: null
                        )
                        : null;
            }

            if (array_key_exists('location', $validated)) {
                $item->location =
                    $validated['location'] !== null
                        ? trim((string) $validated['location'])
                        : null;
            }

            if (array_key_exists('unit', $validated)) {
                $item->unit =
                    strtoupper(trim($validated['unit']));
            }

            if (array_key_exists('inventory_year', $validated)) {
                $item->inventory_year =
                    (int) $validated['inventory_year'];
            }

            if (
                !$isRelease
                && array_key_exists(
                    'ict_assets',
                    $validated
                )
            ) {
                $assetCategory =
                    strtolower(
                        trim(
                            (string) (
                                $validated['category']
                                ?? $item->category
                                ?? ''
                            )
                        )
                    );

                $assetUnit = strtoupper(
                    trim(
                        (string) (
                            $validated['unit']
                            ?? $item->unit
                            ?? ''
                        )
                    )
                );

                $assetExpectedCount =
                    array_key_exists(
                        'currently_available',
                        $validated
                    )
                        ? (int) $validated['currently_available']
                        : (int) ($item->currently_available ?? 0);

                $submittedAssets =
                    $validated['ict_assets'] ?? [];

                $storedAssets =
                    $item->ict_assets ?? [];

                $isIctSubscription =
                    $assetCategory === 'ict'
                    && in_array(
                        $assetUnit,
                        ['MONTH', 'YEAR'],
                        true
                    );

                $isPropertyTrackedOther =
                    in_array(
                        $assetCategory,
                        ['furniture', 'fixtures'],
                        true
                    );

                if ($isIctSubscription) {
                    /*
                     * Subscription ICT uses duration only. It must never be
                     * forced to provide Property Details.
                     */
                    $item->ict_assets = null;
                } elseif ($assetCategory === 'ict') {
                    /*
                     * Normal ICT remains strict: Count must match complete
                     * Property Detail rows.
                     */
                    $item->ict_assets =
                        $this->normalizedIctAssets(
                            $submittedAssets,
                            $assetExpectedCount,
                            true,
                            true
                        );
                } elseif ($isPropertyTrackedOther) {
                    /*
                     * Furniture/Fixtures may contain legacy records created
                     * before Property Details were introduced. Allow those
                     * records to edit Item / Count / Location / Remarks while
                     * ict_assets is still empty.
                     *
                     * Once a Furniture/Fixtures record has real Property
                     * Details (or the user submits them), strict validation is
                     * preserved.
                     */
                    $hasStoredAssets =
                        $this->hasMeaningfulIctAssets(
                            $storedAssets
                        );

                    $hasSubmittedAssets =
                        $this->hasMeaningfulIctAssets(
                            $submittedAssets
                        );

                    if (
                        $hasStoredAssets
                        || $hasSubmittedAssets
                    ) {
                        $item->ict_assets =
                            $this->normalizedIctAssets(
                                $submittedAssets,
                                $assetExpectedCount,
                                true,
                                true
                            );
                    } else {
                        $item->ict_assets = [];
                    }
                } else {
                    $item->ict_assets = null;
                }
            }

            if (array_key_exists('fixed_value', $validated)) {
                $item->fixed_value =
                    $validated['fixed_value'];
            }

            /*
             * Add one Furniture / Fixtures unit.
             *
             * The new unit must have its own Property Details. Count is
             * incremented automatically only after a valid property row exists.
             */
            if ($hasNewOtherAsset) {
                $targetCategory =
                    strtolower(
                        trim(
                            (string) (
                                $validated['category']
                                ?? $item->category
                                ?? ''
                            )
                        )
                    );

                if (
                    !in_array(
                        $targetCategory,
                        ['furniture', 'fixtures'],
                        true
                    )
                ) {
                    throw ValidationException::withMessages([
                        'new_other_asset' =>
                            'Property Details can be added only to Furniture/Fixtures.',
                    ]);
                }

                $submittedAsset =
                    $validated['new_other_asset'];

                $description =
                    trim(
                        (string) (
                            $submittedAsset['description']
                            ?? ''
                        )
                    );

                $propertyNumber =
                    trim(
                        (string) (
                            $submittedAsset['property_number']
                            ?? ''
                        )
                    );

                if ($description === '') {
                    throw ValidationException::withMessages([
                        'new_other_asset.description' =>
                            'Description is required.',
                    ]);
                }

                if ($propertyNumber === '') {
                    throw ValidationException::withMessages([
                        'new_other_asset.property_number' =>
                            'Property Number is required.',
                    ]);
                }

                $oldCount =
                    max(
                        0,
                        (int) (
                            $item->currently_available
                            ?? 0
                        )
                    );

                $assets =
                    $this->normalizedIctAssetRowsForStorage(
                        $item->ict_assets ?? [],
                        $oldCount
                    );

                $newPropertyKey =
                    mb_strtolower(
                        $propertyNumber
                    );

                foreach ($assets as $asset) {
                    $existingPropertyKey =
                        mb_strtolower(
                            trim(
                                (string) (
                                    $asset['property_number']
                                    ?? ''
                                )
                            )
                        );

                    if (
                        $existingPropertyKey !== ''
                        && $existingPropertyKey
                            === $newPropertyKey
                    ) {
                        throw ValidationException::withMessages([
                            'new_other_asset.property_number' =>
                                'Property Number already exists for this item.',
                        ]);
                    }
                }

                $assets[] = [
                    'description' =>
                        $description,

                    'accessories' =>
                        '',

                    'property_number' =>
                        $propertyNumber,

                    'current_user' =>
                        trim(
                            (string) (
                                $submittedAsset['current_user']
                                ?? ''
                            )
                        ),

                    'date_acquired' =>
                        null,

                    'life_span_ended' =>
                        null,

                    'status' =>
                        '',

                    'mr_personnel_id' =>
                        null,

                    'mr' =>
                        '',
                ];

                $item->ict_assets =
                    $assets;

                $item->currently_available =
                    $oldCount + 1;
            }

            /*
             * Count-only Other Items:
             * Emergency Kits / Token & Giveaways.
             */
            if ($hasAddOtherCount) {
                $targetCategory =
                    strtolower(
                        trim(
                            (string) (
                                $validated['category']
                                ?? $item->category
                                ?? ''
                            )
                        )
                    );

                $otherCountCategories = [
                    'emergency_kits',
                    'token_giveaways',
                ];

                if (
                    !in_array(
                        $targetCategory,
                        $otherCountCategories,
                        true
                    )
                ) {
                    throw ValidationException::withMessages([
                        'add_other_count' =>
                            'Quantity to Add is available only for count-based Other Items.',
                    ]);
                }

                $countToAdd =
                    (int) $validated['add_other_count'];

                $item->currently_available =
                    max(
                        0,
                        (int) (
                            $item->currently_available
                            ?? 0
                        )
                    )
                    + $countToAdd;
            }

            /*
             * Direct aggregate correction is legacy-only.
             * Quarter-aware Supplies use quarter_stock instead. ICT uses a global Count/Duration balance.
             */
            if (
                !array_key_exists(
                    'release_quantity',
                    $validated
                )
                &&
                !$hasAddOtherCount
                &&
                !$hasNewOtherAsset
                &&
                array_key_exists(
                    'currently_available',
                    $validated
                )
                &&
                !array_key_exists(
                    'quarter_stock',
                    $validated
                )
            ) {
                $item->currently_available =
                    $validated['currently_available'];
            }

            if (array_key_exists('quarters', $validated)) {
                $item->quarters =
                    $this->normalizedQuarterList(
                        $validated['quarters']
                    );
            }

            if (
                !$isRelease
                && array_key_exists(
                    'quarter_stock',
                    $validated
                )
            ) {
                $targetCategory =
                    strtolower(
                        trim(
                            (string) (
                                $validated['category']
                                ?? $item->category
                            )
                        )
                    );

                if (
                    $targetCategory === 'supplies'
                ) {
                    $targetQuarters =
                        $this->normalizedQuarterList(
                            is_array($item->quarters)
                                ? $item->quarters
                                : []
                        );

                    $newQuarterStock =
                        $this->buildQuarterStock(
                            $targetQuarters,
                            $validated['quarter_stock'],
                            $item
                        );

                    $item->quarter_stock =
                        $newQuarterStock;

                    $item->currently_available =
                        $this->quarterStockCurrentTotal(
                            $newQuarterStock
                        );

                    $newHasFixedBaseline =
                        $targetCategory === 'supplies'
                        && $item->fixed_value !== null
                        && (int) $item->fixed_value > 0;

                    if (!$newHasFixedBaseline) {
                        $item->tracked_released =
                            $this->quarterStockReleasedTotal(
                                $newQuarterStock
                            );
                    }
                }
            }

            if (!$isRelease) {
                $newHasFixedBaseline =
                    $item->fixed_value !== null
                    && (int) $item->fixed_value > 0;

                if (
                    $oldHasFixedBaseline
                    && !$newHasFixedBaseline
                    && strtolower(trim((string) $item->category)) === 'supplies'
                ) {
                    $item->tracked_released = max(
                        (int) ($item->tracked_released ?? 0),
                        (int) $oldDisplayedReleased
                    );
                }
            }

            /*
             * Permanent item remarks may be edited by a normal item update.
             *
             * During a release, the remarks field is TRANSACTION-ONLY
             * and is written to Inventory History below.
             */
            if (
                !$isRelease
                && array_key_exists(
                    'remarks',
                    $validated
                )
            ) {
                $item->remarks =
                    $validated['remarks'];
            }

            $finalCategory =
                strtolower(
                    trim((string) $item->category)
                );

            $otherCategories = [
                'furniture',
                'fixtures',
                'emergency_kits',
                'token_giveaways',
            ];

            $finalIsOther =
                in_array(
                    $finalCategory,
                    $otherCategories,
                    true
                );

            /*
             * Other Items are location-based only.
             * Keep schema-compatibility values internally, but they are
             * intentionally hidden from the Other Items UI.
             */
            if ($finalIsOther) {
                $item->description = null;

                $item->currently_available =
                    (int) ($item->currently_available ?? 0);

                $item->unit = 'N/A';
                $item->inventory_year =
                    $item->inventory_year
                    ?? max(2026, (int) now()->year);
                $item->quarters = [
                    'q1',
                    'q2',
                    'q3',
                    'q4',
                ];
                $item->quarter_stock = null;
                $item->fixed_value = null;

                if (
                    in_array(
                        $finalCategory,
                        ['furniture', 'fixtures'],
                        true
                    )
                ) {
                    /*
                     * Do not force legacy Furniture/Fixtures rows that have
                     * never had Property Details to suddenly provide them just
                     * because another field was edited.
                     */
                    if (
                        $this->hasMeaningfulIctAssets(
                            $item->ict_assets ?? []
                        )
                    ) {
                        $item->ict_assets =
                            $this->normalizedIctAssets(
                                $item->ict_assets ?? [],
                                (int) $item->currently_available,
                                true,
                                true
                            );
                    } else {
                        $item->ict_assets = [];
                    }
                } else {
                    $item->ict_assets = null;
                }

                $item->tracked_released =
                    (int) ($item->tracked_released ?? 0);
            } elseif ($finalCategory === 'ict') {
                $item->description = null;
                $item->location = null;
                $item->fixed_value = null;
                $item->quarters = [];
                $item->quarter_stock = null;

                /*
                 * Keep ICT Item Name and Unit of Measure separate.
                 */
                $item->item =
                    trim(
                        (string) $item->item
                    );

                $item->currently_available =
                    $item->currently_available !== null
                        ? (int) $item->currently_available
                        : 0;
                $item->ict_assets =
                    in_array(
                        strtoupper(trim((string) $item->unit)),
                        ['MONTH', 'YEAR'],
                        true
                    )
                        ? null
                        : $this->normalizedIctAssetRowsForStorage(
                            $item->ict_assets ?? [],
                            (int) $item->currently_available
                        );
                $item->tracked_released =
                    (int) ($item->tracked_released ?? 0);
            } else {
                $item->description = null;
                $item->location = null;
                $item->ict_assets = null;
            }

            $newCurrent =
                $item->currently_available !== null
                    ? (int) $item->currently_available
                    : null;

            $newRemarks =
                $item->remarks;

            $currentChanged =
                $oldCurrent !== $newCurrent;

            $remarksChanged =
                !$isRelease
                &&
                (
                    (string) ($oldRemarks ?? '')
                    !==
                    (string) ($newRemarks ?? '')
                );

            /*
             * For a release transaction, use a clean history-only
             * remark pair. This lets Vue show the release remark
             * without persisting it back into inventory_items.remarks.
             */
            $historyOldRemarks =
                $isRelease
                    ? null
                    : $oldRemarks;

            $historyNewRemarks =
                $isRelease
                    ? (
                        $releaseRemarks !== ''
                            ? $releaseRemarks
                            : null
                    )
                    : $newRemarks;

            $historyRemarksChanged =
                (string) (
                    $historyOldRemarks ?? ''
                )
                !==
                (string) (
                    $historyNewRemarks ?? ''
                );

            /*
             * Saving recalculates generated total_released in MySQL.
             */
            $item->save();
            $item->refresh();

            /*
             * Full audit snapshot AFTER save so generated/casted values are
             * normalized before comparing the record.
             */
            $historyNewData =
                $this->inventoryHistorySnapshot($item);

            /*
             * Release destination is transaction-only metadata.
             * Store it inside new_data JSON so no new history column
             * or migration is required.
             */
            if (
                $isRelease
                && $category !== 'supplies'
                && $releaseDestination !== ''
            ) {
                $historyNewData['release_destination'] =
                    $releaseDestination;
            }

            if (
                $isRelease
                && in_array(
                    $category,
                    ['ict', 'furniture', 'fixtures'],
                    true
                )
                && $releasePropertyNumber !== ''
            ) {
                $historyNewData['release_property_number'] =
                    $releasePropertyNumber;
            }

            if (
                $isRelease
                && $category === 'supplies'
            ) {
                $releaseHistoryQuarters =
                    $this->normalizedQuarterList(
                        is_array($item->quarters)
                            ? $item->quarters
                            : []
                    );

                if (!empty($releaseHistoryQuarters)) {
                    $historyReleaseQuarter =
                        $this->latestActiveQuarter(
                            is_array($item->quarter_stock)
                                ? $item->quarter_stock
                                : [],
                            $releaseHistoryQuarters
                        );

                    if ($historyReleaseQuarter) {
                        $historyNewData['release_quarter'] =
                            $historyReleaseQuarter;
                    }
                }
            }

            $fullRecordChanged =
                $historyOldData !== $historyNewData;

            /**
             * ========================================================
             * HISTORY
             * ========================================================
             *
             * History records the exact stock movement using old/new
             * Currently Available. This remains correct for both:
             * - fixed-baseline items
             * - system-tracked items
             */
            if (
                $fullRecordChanged
                || $currentChanged
                || $remarksChanged
                || $historyRemarksChanged
            ) {
                $history = new InventoryItemHistory();

                $history->inventory_item_id =
                    $item->id;

                $historyTable =
                    $history->getTable();

                /*
                 * New full-audit columns. Schema checks keep the controller
                 * backward-compatible while deploying the migration.
                 */
                if (
                    Schema::hasColumn(
                        $historyTable,
                        'action'
                    )
                ) {
                    $history->action =
                        $isRelease
                            ? 'release'
                            : 'edit';
                }

                if (
                    Schema::hasColumn(
                        $historyTable,
                        'old_data'
                    )
                ) {
                    $history->old_data =
                        $historyOldData;
                }

                if (
                    Schema::hasColumn(
                        $historyTable,
                        'new_data'
                    )
                ) {
                    $history->new_data =
                        $historyNewData;
                }

                if (
                    Schema::hasColumn(
                        $historyTable,
                        'old_currently_available'
                    )
                ) {
                    $history->old_currently_available =
                        $oldCurrent;
                } elseif (
                    Schema::hasColumn(
                        $historyTable,
                        'old_available'
                    )
                ) {
                    $history->old_available =
                        $oldCurrent;
                } elseif (
                    Schema::hasColumn(
                        $historyTable,
                        'legacy_old_available'
                    )
                ) {
                    $history->legacy_old_available =
                        $oldCurrent;
                }

                if (
                    Schema::hasColumn(
                        $historyTable,
                        'new_currently_available'
                    )
                ) {
                    $history->new_currently_available =
                        $newCurrent;
                } elseif (
                    Schema::hasColumn(
                        $historyTable,
                        'new_available'
                    )
                ) {
                    $history->new_available =
                        $newCurrent;
                } elseif (
                    Schema::hasColumn(
                        $historyTable,
                        'legacy_new_available'
                    )
                ) {
                    $history->legacy_new_available =
                        $newCurrent;
                }

                if (
                    Schema::hasColumn(
                        $historyTable,
                        'old_remarks'
                    )
                ) {
                    $history->old_remarks =
                        $historyOldRemarks;
                }

                if (
                    Schema::hasColumn(
                        $historyTable,
                        'new_remarks'
                    )
                ) {
                    $history->new_remarks =
                        $historyNewRemarks;
                }

                if (
                    Schema::hasColumn(
                        $historyTable,
                        'updated_by'
                    )
                ) {
                    $history->updated_by =
                        $userId;
                }

                if (
                    Schema::hasColumn(
                        $historyTable,
                        'updated_by_name'
                    )
                ) {
                    $history->updated_by_name =
                        $userName;
                }

                $history->save();
            }

            Log::info('Inventory item updated', [
                'inventory_item_id' =>
                    $item->id,

                'category' =>
                    $item->category,

                'fixed_value' =>
                    $item->fixed_value,

                'old_currently_available' =>
                    $oldCurrent,

                'new_currently_available' =>
                    $newCurrent,

                'total_released' =>
                    $item->total_released,

                'old_tracked_released' =>
                    $oldTrackedReleased,

                'new_tracked_released' =>
                    (int) ($item->tracked_released ?? 0),

                'release_remarks' =>
                    $releaseRemarks,

                'updated_by' =>
                    $userId,

                'updated_by_name' =>
                    $userName,
            ]);
        });

        return back()->with(
            'success',
            'Inventory item updated successfully.'
        );
    }

    /**
     * Inventory release/update history.
     */
    public function history(
        InventoryItem $inventoryItem
    ) {
        $histories = $inventoryItem
            ->histories()
            ->get()
            ->map(function ($history) {
                $oldData =
                    is_array($history->old_data ?? null)
                        ? $history->old_data
                        : [];

                $newData =
                    is_array($history->new_data ?? null)
                        ? $history->new_data
                        : [];

                $changes =
                    $this->inventoryHistoryChanges(
                        $oldData,
                        $newData
                    );

                $oldCurrent =
                    $history->old_currently_available
                    ?? $history->old_available
                    ?? $history->legacy_old_available
                    ?? null;

                $newCurrent =
                    $history->new_currently_available
                    ?? $history->new_available
                    ?? $history->legacy_new_available
                    ?? null;

                $action =
                    $history->action
                    ?? null;

                /*
                 * Resolve category/unit before any release-history logic.
                 * Property-based ICT and Furniture/Fixtures releases need
                 * these values before building their synthetic changes.
                 */
                $historyCategory =
                    strtolower(
                        trim(
                            (string) (
                                $newData['category']
                                ?? $oldData['category']
                                ?? $inventoryItem->category
                                ?? ''
                            )
                        )
                    );

                $historyUnit =
                    strtoupper(
                        trim(
                            (string) (
                                $newData['unit']
                                ?? $oldData['unit']
                                ?? $inventoryItem->unit
                                ?? ''
                            )
                        )
                    );

                /*
                 * When a quarter is newly activated, show the exact
                 * quantity entered by the user instead of only showing
                 * the resulting aggregate Currently Available value.
                 *
                 * This does NOT restore the removed "Quarter Balances"
                 * history row.
                 */
                if ($action !== 'release') {
                    $oldQuarterStock =
                        is_array(
                            $oldData['quarter_stock']
                            ?? null
                        )
                            ? $oldData['quarter_stock']
                            : [];

                    $newQuarterStock =
                        is_array(
                            $newData['quarter_stock']
                            ?? null
                        )
                            ? $newData['quarter_stock']
                            : [];

                    foreach (
                        ['q1', 'q2', 'q3', 'q4']
                        as $quarter
                    ) {
                        $oldEntry =
                            is_array(
                                $oldQuarterStock[$quarter]
                                ?? null
                            )
                                ? $oldQuarterStock[$quarter]
                                : [];

                        $newEntry =
                            is_array(
                                $newQuarterStock[$quarter]
                                ?? null
                            )
                                ? $newQuarterStock[$quarter]
                                : [];

                        $oldAdded =
                            max(
                                0,
                                (int) (
                                    $oldEntry['added']
                                    ?? 0
                                )
                            );

                        $newAdded =
                            max(
                                0,
                                (int) (
                                    $newEntry['added']
                                    ?? 0
                                )
                            );

                        /*
                         * New quarter activation / newly added stock.
                         */
                        if ($newAdded > $oldAdded) {
                            $changes[] = [
                                'field' =>
                                    'quarter_quantity_added',

                                'label' =>
                                    'Quantity Added · '
                                    . strtoupper($quarter),

                                'old' =>
                                    null,

                                'new' =>
                                    $newAdded - $oldAdded,

                                'single' =>
                                    true,
                            ];
                        }
                    }
                }

                /*
                 * A release is an action rather than a directly editable
                 * field, so expose the exact released quantity as a
                 * synthetic history change.
                 */
                $historyReleasePropertyNumber =
                    trim(
                        (string) (
                            $newData['release_property_number']
                            ?? ''
                        )
                    );

                if (
                    $action === 'release'
                    && in_array(
                        $historyCategory,
                        ['ict', 'furniture', 'fixtures'],
                        true
                    )
                    && $historyReleasePropertyNumber !== ''
                ) {
                    $changes = array_values(
                        array_filter(
                            $changes,
                            fn ($change) =>
                                ($change['field'] ?? '') !== 'ict_assets'
                        )
                    );

                    array_unshift(
                        $changes,
                        [
                            'field' => 'release_quantity',
                            'label' => 'Quantity Released',
                            'old' => null,
                            'new' => 1,
                            'single' => true,
                            'asset_property_number' =>
                                $historyReleasePropertyNumber,
                            'asset_property_numbers' =>
                                [$historyReleasePropertyNumber],
                        ]
                    );

                    $changes[] = [
                        'field' => 'release_property_number',
                        'label' => 'Property Number',
                        'old' => null,
                        'new' => $historyReleasePropertyNumber,
                        'single' => true,
                        'asset_property_number' =>
                            $historyReleasePropertyNumber,
                        'asset_property_numbers' =>
                            [$historyReleasePropertyNumber],
                    ];
                }

                if (
                    $action === 'release'
                    && $historyReleasePropertyNumber === ''
                    && $oldCurrent !== null
                    && $newCurrent !== null
                    && (int) $oldCurrent > (int) $newCurrent
                ) {
                    $releaseLabel =
                        $historyCategory === 'ict'
                            && $historyUnit === 'MONTH'
                                ? 'Month(s) Released'
                                : (
                                    $historyCategory === 'ict'
                                    && $historyUnit === 'YEAR'
                                        ? 'Year(s) Released'
                                        : 'Quantity Released'
                                );

                    array_unshift(
                        $changes,
                        [
                            'field' =>
                                'release_quantity',

                            'label' =>
                                $releaseLabel,

                            'old' =>
                                null,

                            'new' =>
                                (int) $oldCurrent
                                - (int) $newCurrent,

                            'single' =>
                                true,
                        ]
                    );
                }

                if (
                    $action === 'release'
                    && trim(
                        (string) (
                            $newData['release_destination']
                            ?? ''
                        )
                    ) !== ''
                ) {
                    $changes[] = [
                        'field' =>
                            'release_destination',

                        'label' =>
                            (
                                in_array(
                                    $historyCategory,
                                    ['ict', 'furniture', 'fixtures'],
                                    true
                                )
                                && $historyReleasePropertyNumber !== ''
                            )
                                ? 'Current User / Released To'
                                : 'Released To / Destination',

                        'old' =>
                            null,

                        'new' =>
                            $newData['release_destination'],

                        'single' =>
                            true,

                        'asset_property_number' =>
                            $historyReleasePropertyNumber !== ''
                                ? $historyReleasePropertyNumber
                                : null,

                        'asset_property_numbers' =>
                            $historyReleasePropertyNumber !== ''
                                ? [$historyReleasePropertyNumber]
                                : [],
                    ];
                }

                /*
                 * Release remarks are transaction-only and do not modify the
                 * permanent inventory_items.remarks field, so add them to
                 * the detailed changes explicitly.
                 */
                if (
                    $action === 'release'
                    && trim(
                        (string) (
                            $history->new_remarks
                            ?? ''
                        )
                    ) !== ''
                ) {
                    $changes[] = [
                        'field' =>
                            'remarks',

                        'label' =>
                            'Remarks',

                        'old' =>
                            null,

                        'new' =>
                            $history->new_remarks,

                        'single' =>
                            true,

                        'asset_property_number' =>
                            $historyReleasePropertyNumber !== ''
                                ? $historyReleasePropertyNumber
                                : null,

                        'asset_property_numbers' =>
                            $historyReleasePropertyNumber !== ''
                                ? [$historyReleasePropertyNumber]
                                : [],
                    ];
                }

                $propertyNumbers = [];

                foreach ($changes as $change) {
                    $changePropertyNumbers =
                        is_array(
                            $change['asset_property_numbers']
                            ?? null
                        )
                            ? $change['asset_property_numbers']
                            : [];

                    foreach (
                        $changePropertyNumbers
                        as $propertyNumber
                    ) {
                        $propertyNumber =
                            trim(
                                (string) $propertyNumber
                            );

                        if ($propertyNumber !== '') {
                            $propertyNumbers[] =
                                $propertyNumber;
                        }
                    }

                    $singleProperty =
                        trim(
                            (string) (
                                $change['asset_property_number']
                                ?? ''
                            )
                        );

                    if ($singleProperty !== '') {
                        $propertyNumbers[] =
                            $singleProperty;
                    }
                }

                if ($historyReleasePropertyNumber !== '') {
                    $propertyNumbers[] =
                        $historyReleasePropertyNumber;
                }

                $propertyNumbers =
                    array_values(
                        array_unique(
                            array_filter(
                                $propertyNumbers,
                                fn ($value) =>
                                    trim((string) $value) !== ''
                            )
                        )
                    );

                $changeFields =
                    array_values(
                        array_map(
                            fn ($change) =>
                                (string) (
                                    $change['field']
                                    ?? ''
                                ),
                            $changes
                        )
                    );

                $hasAddedProperty =
                    in_array(
                        'ict_asset_added',
                        $changeFields,
                        true
                    );

                $hasQuarterRemarksEdit =
                    in_array(
                        'quarter_remarks',
                        $changeFields,
                        true
                    );

                $hasPropertyEdit =
                    count(
                        array_filter(
                            $changeFields,
                            fn ($field) =>
                                str_starts_with(
                                    $field,
                                    'ict_asset_'
                                )
                                && !in_array(
                                    $field,
                                    [
                                        'ict_asset_added',
                                        'ict_asset_removed',
                                    ],
                                    true
                                )
                        )
                    ) > 0;

                if ($action === 'release') {
                    $eventTitle =
                        $historyReleasePropertyNumber !== ''
                            ? 'Released Property'
                            : 'Released Stock';

                    $destination =
                        trim(
                            (string) (
                                $newData['release_destination']
                                ?? ''
                            )
                        );

                    $eventSummary =
                        $historyReleasePropertyNumber !== ''
                            ? (
                                'Property '
                                . $historyReleasePropertyNumber
                                . (
                                    $destination !== ''
                                        ? ' released to ' . $destination
                                        : ' was released'
                                )
                            )
                            : 'Inventory quantity was released.';
                } elseif ($hasAddedProperty) {
                    $eventTitle =
                        'Added ICT Unit';

                    $eventSummary =
                        !empty($propertyNumbers)
                            ? 'Property '
                                . $propertyNumbers[0]
                                . ' was added.'
                            : 'A new ICT unit was added.';
                } elseif ($hasQuarterRemarksEdit) {
                    $eventTitle =
                        'Updated Quarter Remarks';

                    $quarterLabels =
                        array_values(
                            array_unique(
                                array_filter(
                                    array_map(
                                        fn ($change) =>
                                            ($change['field'] ?? '') === 'quarter_remarks'
                                                ? trim(
                                                    (string) (
                                                        $change['label']
                                                        ?? ''
                                                    )
                                                )
                                                : '',
                                        $changes
                                    )
                                )
                            )
                        );

                    $eventSummary =
                        !empty($quarterLabels)
                            ? implode(
                                ', ',
                                array_slice(
                                    $quarterLabels,
                                    0,
                                    2
                                )
                            )
                                . (
                                    count($quarterLabels) > 2
                                        ? ' and more'
                                        : ''
                                )
                                . ' updated.'
                            : 'Quarter remarks were updated.';
                } elseif ($hasPropertyEdit) {
                    $eventTitle =
                        'Edited Property Details';

                    $eventSummary =
                        !empty($propertyNumbers)
                            ? 'Property '
                                . $propertyNumbers[0]
                                . ' was updated.'
                            : 'ICT Property Details were updated.';
                } else {
                    $eventTitle =
                        'Edited Item Details';

                    $changedLabels =
                        array_values(
                            array_unique(
                                array_filter(
                                    array_map(
                                        fn ($change) =>
                                            trim(
                                                (string) (
                                                    $change['label']
                                                    ?? ''
                                                )
                                            ),
                                        $changes
                                    )
                                )
                            )
                        );

                    $eventSummary =
                        !empty($changedLabels)
                            ? implode(
                                ', ',
                                array_slice(
                                    $changedLabels,
                                    0,
                                    3
                                )
                            )
                                . (
                                    count($changedLabels) > 3
                                        ? ' and more'
                                        : ''
                                )
                                . ' updated.'
                            : 'Inventory record was updated.';
                }

                return [
                    'id' =>
                        $history->id,

                    'action' =>
                        $action,

                    'event_title' =>
                        $eventTitle,

                    'event_summary' =>
                        $eventSummary,

                    'property_numbers' =>
                        $propertyNumbers,

                    'changes' =>
                        $changes,

                    'old_data' =>
                        $oldData,

                    'new_data' =>
                        $newData,

                    'old_currently_available' =>
                        $oldCurrent,

                    'new_currently_available' =>
                        $newCurrent,

                    /* Compatibility aliases for current Vue helpers. */
                    'old_available' =>
                        $oldCurrent,

                    'new_available' =>
                        $newCurrent,

                    'old_remarks' =>
                        $history->old_remarks,

                    'new_remarks' =>
                        $history->new_remarks,

                    'updated_by' =>
                        $history->updated_by,

                    'updated_by_name' =>
                        $history->updated_by_name,

                    'created_at' =>
                        $history->created_at
                            ?->timezone('Asia/Manila')
                            ->format('M d, Y h:i A'),
                ];
            });

        $inventoryItem->refresh();

        return response()->json([
            'item' => [
                'id' =>
                    $inventoryItem->id,

                'category' =>
                    strtolower(
                        trim((string) $inventoryItem->category)
                    ),

                'item' =>
                    $inventoryItem->item,

                'unit' =>
                    $inventoryItem->unit,

                'fixed_value' =>
                    $inventoryItem->fixed_value,

                'currently_available' =>
                    $inventoryItem->currently_available,

                /* Generated when Fixed Value > 0. */
                'total_released' =>
                    $inventoryItem->total_released,

                /* Used when there is no usable Fixed Value. */
                'tracked_released' =>
                    (int) ($inventoryItem->tracked_released ?? 0),

                'remarks' =>
                    $inventoryItem->remarks,
            ],

            'histories' =>
                $histories,
        ]);
    }

    /**
     * Return only user-visible/editable inventory values for audit history.
     *
     * Internal/generated fields are deliberately excluded so History stays
     * understandable to users and does not show implementation noise.
     */
    private function inventoryHistorySnapshot(
        InventoryItem $item
    ): array {
        $quarters =
            is_array($item->quarters)
                ? $item->quarters
                : [];

        $quarterOrder = [
            'q1' => 1,
            'q2' => 2,
            'q3' => 3,
            'q4' => 4,
        ];

        $quarters = array_values(
            array_unique(
                array_filter(
                    array_map(
                        fn ($quarter) =>
                            strtolower(
                                trim((string) $quarter)
                            ),
                        $quarters
                    ),
                    fn ($quarter) =>
                        array_key_exists(
                            $quarter,
                            $quarterOrder
                        )
                )
            )
        );

        usort(
            $quarters,
            fn ($a, $b) =>
                $quarterOrder[$a]
                <=>
                $quarterOrder[$b]
        );

        $category =
            strtolower(
                trim((string) $item->category)
            );

        $isOtherItem =
            in_array(
                $category,
                [
                    'furniture',
                    'fixtures',
                    'emergency_kits',
                    'token_giveaways',
                ],
                true
            );

        return [
            'category' =>
                $category,

            'item' =>
                trim((string) $item->item),

            'description' => null,

            'location' =>
                $isOtherItem
                    ? (
                        $item->location !== null
                            ? trim((string) $item->location)
                            : null
                    )
                    : null,

            'unit' =>
                $isOtherItem
                    ? null
                    : strtoupper(
                        trim((string) $item->unit)
                    ),

            'inventory_year' =>
                $isOtherItem
                    ? null
                    : (
                        $item->inventory_year !== null
                            ? (int) $item->inventory_year
                            : null
                    ),

            'quarters' =>
                $category === 'supplies'
                    ? $quarters
                    : [],

            'quarter_stock' =>
                $category === 'supplies'
                    ? $this->normalizedStoredQuarterStock(
                        $item->quarter_stock
                    )
                    : [],

            'fixed_value' =>
                $item->fixed_value !== null
                    ? (int) $item->fixed_value
                    : null,

            'currently_available' =>
                $item->currently_available !== null
                    ? (int) $item->currently_available
                    : null,

            'ict_assets' =>
                in_array(
                    $category,
                    ['ict', 'furniture', 'fixtures'],
                    true
                )
                    ? $this->normalizedIctAssets(
                        $item->ict_assets ?? []
                    )
                    : [],

            'remarks' =>
                $item->remarks !== null
                    ? (string) $item->remarks
                    : null,
        ];
    }

    /**
     * Build readable per-quarter remarks history for Supplies.
     */
    private function inventoryQuarterRemarksHistoryChanges(
        mixed $oldQuarterStock,
        mixed $newQuarterStock
    ): array {
        $oldStock =
            is_array($oldQuarterStock)
                ? $oldQuarterStock
                : [];

        $newStock =
            is_array($newQuarterStock)
                ? $newQuarterStock
                : [];

        $changes = [];

        foreach (
            ['q1', 'q2', 'q3', 'q4']
            as $quarter
        ) {
            $oldRemarks =
                trim(
                    (string) (
                        $oldStock[$quarter]['remarks']
                        ?? ''
                    )
                );

            $newRemarks =
                trim(
                    (string) (
                        $newStock[$quarter]['remarks']
                        ?? ''
                    )
                );

            if ($oldRemarks === $newRemarks) {
                continue;
            }

            $changes[] = [
                'field' =>
                    'quarter_remarks',

                'label' =>
                    strtoupper($quarter)
                    . ' Remarks',

                'old' =>
                    $oldRemarks !== ''
                        ? $oldRemarks
                        : null,

                'new' =>
                    $newRemarks !== ''
                        ? $newRemarks
                        : null,

                'single' =>
                    false,

                'quarter' =>
                    $quarter,
            ];
        }

        return $changes;
    }


    /**
     * Build readable per-property history changes.
     */
    private function inventoryAssetHistoryChanges(
        mixed $oldAssets,
        mixed $newAssets
    ): array {
        $oldRows =
            is_array($oldAssets)
                ? array_values($oldAssets)
                : [];

        $newRows =
            is_array($newAssets)
                ? array_values($newAssets)
                : [];

        $maxRows =
            max(
                count($oldRows),
                count($newRows)
            );

        $changes = [];

        for ($index = 0; $index < $maxRows; $index++) {
            $oldAsset =
                is_array($oldRows[$index] ?? null)
                    ? $oldRows[$index]
                    : null;

            $newAsset =
                is_array($newRows[$index] ?? null)
                    ? $newRows[$index]
                    : null;

            if ($oldAsset === null && $newAsset === null) {
                continue;
            }

            $oldProperty =
                trim(
                    (string) (
                        $oldAsset['property_number']
                        ?? ''
                    )
                );

            $newProperty =
                trim(
                    (string) (
                        $newAsset['property_number']
                        ?? ''
                    )
                );

            $propertyNumbers =
                array_values(
                    array_unique(
                        array_filter(
                            [
                                $oldProperty,
                                $newProperty,
                            ],
                            fn ($value) =>
                                trim((string) $value) !== ''
                        )
                    )
                );

            $displayProperty =
                $newProperty !== ''
                    ? $newProperty
                    : (
                        $oldProperty !== ''
                            ? $oldProperty
                            : 'Row ' . ($index + 1)
                    );

            if ($oldAsset === null && $newAsset !== null) {
                $summaryParts = [];

                if ($newProperty !== '') {
                    $summaryParts[] =
                        'Property ' . $newProperty;
                }

                $description =
                    trim(
                        (string) (
                            $newAsset['description']
                            ?? ''
                        )
                    );

                if ($description !== '') {
                    $summaryParts[] = $description;
                }

                $status =
                    strtolower(
                        trim(
                            (string) (
                                $newAsset['status']
                                ?? ''
                            )
                        )
                    );

                if ($status === 'for_return') {
                    $status = 'returned';
                }

                if ($status !== '') {
                    $summaryParts[] =
                        $status === 'returned'
                            ? 'Returned'
                            : 'Working';
                }

                $mr =
                    trim(
                        (string) (
                            $newAsset['mr']
                            ?? ''
                        )
                    );

                if ($mr !== '') {
                    $summaryParts[] =
                        'MR: ' . $mr;
                }

                $changes[] = [
                    'field' => 'ict_asset_added',
                    'label' => 'ICT Unit Added',
                    'old' => null,
                    'new' =>
                        !empty($summaryParts)
                            ? implode(' · ', $summaryParts)
                            : 'New ICT unit',
                    'single' => true,
                    'asset_index' => $index,
                    'asset_property_number' =>
                        $newProperty !== ''
                            ? $newProperty
                            : null,
                    'asset_property_numbers' =>
                        $propertyNumbers,
                ];

                continue;
            }

            if ($oldAsset !== null && $newAsset === null) {
                $changes[] = [
                    'field' => 'ict_asset_removed',
                    'label' => 'ICT Unit Removed',
                    'old' => null,
                    'new' =>
                        $oldProperty !== ''
                            ? 'Property ' . $oldProperty
                            : 'Property Row ' . ($index + 1),
                    'single' => true,
                    'asset_index' => $index,
                    'asset_property_number' =>
                        $oldProperty !== ''
                            ? $oldProperty
                            : null,
                    'asset_property_numbers' =>
                        $propertyNumbers,
                ];

                continue;
            }

            $assetFields = [
                'description' => 'Description',
                'accessories' => 'Accessories',
                'property_number' => 'Property Number',
                'current_user' => 'Current User',
                'date_acquired' => 'Date Acquired',
                'life_span_ended' => 'Life Span Ended',
                'status' => 'Status',
                'mr' => 'MR',
            ];

            foreach ($assetFields as $field => $label) {
                $oldValue =
                    trim(
                        (string) (
                            $oldAsset[$field]
                            ?? ''
                        )
                    );

                $newValue =
                    trim(
                        (string) (
                            $newAsset[$field]
                            ?? ''
                        )
                    );

                if ($oldValue === $newValue) {
                    continue;
                }

                $changes[] = [
                    'field' =>
                        'ict_asset_' . $field,
                    'label' =>
                        'Property '
                        . $displayProperty
                        . ' · '
                        . $label,
                    'old' =>
                        $oldValue !== ''
                            ? $oldValue
                            : null,
                    'new' =>
                        $newValue !== ''
                            ? $newValue
                            : null,
                    'single' => false,
                    'asset_index' => $index,
                    'asset_property_number' =>
                        str_starts_with(
                            $displayProperty,
                            'Row '
                        )
                            ? null
                            : $displayProperty,
                    'asset_property_numbers' =>
                        $propertyNumbers,
                ];
            }
        }

        return $changes;
    }


    /**
     * Convert old/new audit snapshots into a clean list of changed fields.
     */
    private function inventoryHistoryChanges(
        array $oldData,
        array $newData
    ): array {
        if (
            empty($oldData)
            || empty($newData)
        ) {
            return [];
        }

        $historyCategory =
            strtolower(
                trim(
                    (string) (
                        $newData['category']
                        ?? $oldData['category']
                        ?? ''
                    )
                )
            );

        $countedOtherCategories = [
            'furniture',
            'fixtures',
            'emergency_kits',
            'token_giveaways',
        ];

        $historyUnit =
            strtoupper(
                trim(
                    (string) (
                        $newData['unit']
                        ?? $oldData['unit']
                        ?? ''
                    )
                )
            );

        if ($historyCategory === 'ict') {
            if ($historyUnit === 'MONTH') {
                $currentAvailableLabel =
                    'Month(s)';
            } elseif ($historyUnit === 'YEAR') {
                $currentAvailableLabel =
                    'Year(s)';
            } else {
                $currentAvailableLabel =
                    'Count';
            }
        } else {
            $currentAvailableLabel =
                in_array(
                    $historyCategory,
                    $countedOtherCategories,
                    true
                )
                    ? 'Count'
                    : 'Currently Available in SPD';
        }

        $fields = [
            'category' => 'Category',
        ];

        if ($historyCategory === 'ict') {
            $fields['item'] =
                'Item Name';
            $fields['unit'] =
                'Unit of Measure';
            $fields['inventory_year'] =
                'Inventory Year';
        } else {
            $fields['item'] =
                'Item Name';
            $fields['location'] =
                'Location';
            $fields['unit'] =
                'Unit';
            $fields['inventory_year'] =
                'Inventory Year';
        }

        if ($historyCategory === 'supplies') {
            $fields['quarters'] = 'Quarter(s)';
            $fields['quarter_stock'] =
                'Quarter Details';
            $fields['fixed_value'] = 'Fixed Value';
        }

        $fields['currently_available'] =
            $currentAvailableLabel;

        if (
            in_array(
                $historyCategory,
                ['ict', 'furniture', 'fixtures'],
                true
            )
        ) {
            $fields['ict_assets'] =
                'Property Details';
        }

        $fields['remarks'] = 'Remarks';

        $changes = [];

        foreach ($fields as $field => $label) {
            $oldValue =
                $oldData[$field]
                ?? null;

            $newValue =
                $newData[$field]
                ?? null;

            if ($oldValue === $newValue) {
                continue;
            }

            if ($field === 'quarter_stock') {
                $changes =
                    array_merge(
                        $changes,
                        $this->inventoryQuarterRemarksHistoryChanges(
                            $oldValue,
                            $newValue
                        )
                    );

                continue;
            }

            if ($field === 'ict_assets') {
                $changes =
                    array_merge(
                        $changes,
                        $this->inventoryAssetHistoryChanges(
                            $oldValue,
                            $newValue
                        )
                    );

                continue;
            }

            $changes[] = [
                'field' =>
                    $field,

                'label' =>
                    $label,

                'old' =>
                    $oldValue,

                'new' =>
                    $newValue,

                'single' =>
                    false,
            ];
        }

        return $changes;
    }

    /**
     * Normalize assigned quarter names.
     */
    private function normalizedQuarterList(
        mixed $quarters
    ): array {
        $allowed = [
            'q1',
            'q2',
            'q3',
            'q4',
        ];

        if (!is_array($quarters)) {
            return [];
        }

        $normalized =
            array_values(
                array_unique(
                    array_filter(
                        array_map(
                            fn ($quarter) =>
                                strtolower(
                                    trim(
                                        (string) $quarter
                                    )
                                ),
                            $quarters
                        ),
                        fn ($quarter) =>
                            in_array(
                                $quarter,
                                $allowed,
                                true
                            )
                    )
                )
            );

        usort(
            $normalized,
            fn ($a, $b) =>
                array_search(
                    $a,
                    $allowed,
                    true
                )
                <=>
                array_search(
                    $b,
                    $allowed,
                    true
                )
        );

        return $normalized;
    }

    private function quarterStockEntryHasActivity(
        array $entry
    ): bool {
        foreach (
            [
                'opening',
                'carryover',
                'added',
                'current',
                'released',
            ]
            as $field
        ) {
            if (
                (int) (
                    $entry[$field]
                    ?? 0
                ) > 0
            ) {
                return true;
            }
        }

        return false;
    }

    /**
     * Return the latest quarter that has actual stock activity.
     * Completely zero future quarters are dormant.
     */
    private function latestActiveQuarter(
        array $quarterStock,
        array $assignedQuarters = []
    ): ?string {
        $normalized =
            $this->normalizedStoredQuarterStock(
                $quarterStock
            );

        $latest = null;

        foreach (
            ['q1', 'q2', 'q3', 'q4']
            as $quarter
        ) {
            if (
                isset($normalized[$quarter])
                && $this->quarterStockEntryHasActivity(
                    $normalized[$quarter]
                )
            ) {
                $latest = $quarter;
            }
        }

        if ($latest !== null) {
            return $latest;
        }

        $assigned =
            $this->normalizedQuarterList(
                $assignedQuarters
            );

        return !empty($assigned)
            ? $assigned[0]
            : null;
    }

