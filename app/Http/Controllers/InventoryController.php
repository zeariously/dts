    /**
     * Normalize ICT asset dates. Legacy four-digit years are converted
     * to December 31 of that year for backward compatibility.
     */
    private function normalizedInventoryAssetDate(
        mixed $value
    ): ?string {
        $raw =
            trim((string) ($value ?? ''));

        if ($raw === '') {
            return null;
        }

        if (preg_match('/^\d{4}$/', $raw)) {
            $year = (int) $raw;

            return (
                $year >= 1900
                && $year <= 2200
            )
                ? sprintf('%04d-12-31', $year)
                : null;
        }

        if (
            !preg_match(
                '/^(\d{4})-(\d{2})-(\d{2})$/',
                $raw,
                $matches
            )
        ) {
            return null;
        }

        $year = (int) $matches[1];
        $month = (int) $matches[2];
        $day = (int) $matches[3];

        if (
            $year < 1900
            || $year > 2200
            || !checkdate($month, $day, $year)
        ) {
            return null;
        }

        return sprintf(
            '%04d-%02d-%02d',
            $year,
            $month,
            $day
        );
    }


