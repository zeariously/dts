    /**
     * Clean a stored quarter_stock JSON value.
     */
    private function normalizedStoredQuarterStock(
        mixed $quarterStock
    ): array {
        if (!is_array($quarterStock)) {
            return [];
        }

        $normalized = [];

        foreach (
            ['q1', 'q2', 'q3', 'q4']
            as $quarter
        ) {
            $entry =
                $quarterStock[$quarter]
                ?? null;

            if (!is_array($entry)) {
                continue;
            }

            if (
                !array_key_exists(
                    'current',
                    $entry
                )
            ) {
                continue;
            }

            $current =
                max(
                    0,
                    (int) $entry['current']
                );

            $released =
                max(
                    0,
                    (int) (
                        $entry['released']
                        ?? 0
                    )
                );

            $opening =
                max(
                    0,
                    (int) (
                        $entry['opening']
                        ?? (
                            $current
                            + $released
                        )
                    )
                );

            $carryover =
                max(
                    0,
                    (int) (
                        $entry['carryover']
                        ?? 0
                    )
                );

            $added =
                max(
                    0,
                    (int) (
                        $entry['added']
                        ?? max(
                            0,
                            $opening
                            - $carryover
                        )
                    )
                );

            $normalized[$quarter] = [
                'opening' =>
                    $opening,

                'carryover' =>
                    $carryover,

                'added' =>
                    $added,

                'current' =>
                    $current,

                'released' =>
                    $released,

                'remarks' =>
                    trim(
                        (string) (
                            $entry['remarks']
                            ?? ''
                        )
                    ),
            ];
        }

        /*
         * Repair the carryover chain for ACTIVE quarters only.
         * Completely zero entries are future/dormant quarters and
         * must not automatically become active just because the item
         * is assigned to All Quarters.
         */
        $previousCurrent = 0;
        $hasPreviousActive = false;

        foreach (
            ['q1', 'q2', 'q3', 'q4']
            as $quarter
        ) {
            if (!isset($normalized[$quarter])) {
                continue;
            }

            $entry =
                $normalized[$quarter];

            if (
                !$this->quarterStockEntryHasActivity(
                    $entry
                )
            ) {
                $normalized[$quarter] = [
                    'opening' => 0,
                    'carryover' => 0,
                    'added' => 0,
                    'current' => 0,
                    'released' => 0,
                    'remarks' =>
                        trim(
                            (string) (
                                $entry['remarks']
                                ?? ''
                            )
                        ),
                ];

                continue;
            }

            $released =
                max(
                    0,
                    (int) (
                        $entry['released']
                        ?? 0
                    )
                );

            $storedCarryover =
                max(
                    0,
                    (int) (
                        $entry['carryover']
                        ?? 0
                    )
                );

            $storedOpening =
                max(
                    0,
                    (int) (
                        $entry['opening']
                        ?? 0
                    )
                );

            $added =
                max(
                    0,
                    (int) (
                        $entry['added']
                        ?? max(
                            0,
                            $storedOpening
                            - $storedCarryover
                        )
                    )
                );

            $carryover =
                $hasPreviousActive
                    ? $previousCurrent
                    : 0;

            $opening =
                $carryover
                + $added;

            $current =
                max(
                    0,
                    $opening
                    - $released
                );

            $normalized[$quarter] = [
                'opening' =>
                    $opening,

                'carryover' =>
                    $carryover,

                'added' =>
                    $added,

                'current' =>
                    $current,

                'released' =>
                    $released,

                'remarks' =>
                    trim(
                        (string) (
                            $entry['remarks']
                            ?? ''
                        )
                    ),
            ];

            $previousCurrent =
                $current;

            $hasPreviousActive =
                true;
        }

        return $normalized;
    }

    /**
     * Build quarter balances for Add/Edit.
     */
    private function buildQuarterStock(
        array $quarters,
        mixed $rawQuarterStock,
        ?InventoryItem $item = null
    ): array {
        $raw =
            is_array($rawQuarterStock)
                ? $rawQuarterStock
                : [];

        $existing =
            $item
                ? $this->normalizedStoredQuarterStock(
                    $item->quarter_stock
                )
                : [];

        $legacyReleased = 0;

        if (
            $item
            && empty($existing)
            && count($quarters) === 1
        ) {
            $legacyCurrent =
                $item->currently_available !== null
                    ? (int) $item->currently_available
                    : 0;

            $hasFixedBaseline =
                $item->fixed_value !== null
                && (int) $item->fixed_value > 0;

            $legacyReleased =
                $hasFixedBaseline
                    ? max(
                        0,
                        (int) $item->fixed_value
                        - $legacyCurrent
                    )
                    : max(
                        0,
                        (int) (
                            $item->tracked_released
                            ?? 0
                        )
                    );
        }

        $result = [];
        $previousCurrent = 0;

        foreach ($quarters as $quarter) {
            $rawEntry =
                $raw[$quarter]
                ?? [];

            if (
                !is_array($rawEntry)
                || !array_key_exists(
                    'current',
                    $rawEntry
                )
            ) {
                throw ValidationException::withMessages([
                    "quarter_stock.{$quarter}.current" =>
                        'Enter the quantity for '
                        . strtoupper($quarter)
                        . '.',
                ]);
            }

            $rawValue =
                (int) $rawEntry['current'];

            $rawRemarks =
                trim(
                    (string) (
                        $rawEntry['remarks']
                        ?? ''
                    )
                );

            if ($rawValue < 0) {
                throw ValidationException::withMessages([
                    "quarter_stock.{$quarter}.current" =>
                        'Quarter quantity cannot be negative.',
                ]);
            }

            $existingEntry =
                $existing[$quarter]
                ?? null;

            $existingStarted =
                is_array($existingEntry)
                && $this->quarterStockEntryHasActivity(
                    $existingEntry
                );

            $activateRequested =
                filter_var(
                    $rawEntry['activate']
                    ?? false,
                    FILTER_VALIDATE_BOOLEAN
                );

            /*
             * EXISTING ACTIVE QUARTER:
             * rawValue is a remaining-balance correction.
             */
            if ($existingStarted) {
                $released =
                    max(
                        0,
                        (int) (
                            $existingEntry[
                                'released'
                            ]
                            ?? 0
                        )
                    );

                $carryover =
                    max(
                        0,
                        (int) (
                            $existingEntry[
                                'carryover'
                            ]
                            ?? 0
                        )
                    );

                $opening =
                    $rawValue
                    + $released;

                $added =
                    max(
                        0,
                        $opening
                        - $carryover
                    );

                $result[$quarter] = [
                    'opening' =>
                        $opening,

                    'carryover' =>
                        $carryover,

                    'added' =>
                        $added,

                    'current' =>
                        $rawValue,

                    'released' =>
                        $released,

                    'remarks' =>
                        $rawRemarks,
                ];

                $previousCurrent =
                    $rawValue;

                continue;
            }

            /*
             * EXISTING DORMANT FUTURE QUARTER:
             * Keep it zero until the user actually enters/activates it.
             *
             * Entering a positive new quantity automatically activates
             * it. The frontend also sends activate=true when the user
             * edits/toggles a dormant quarter, including a zero-addition
             * carryover-only activation.
             */
            if (
                is_array($existingEntry)
                && !$activateRequested
                && $rawValue === 0
            ) {
                $result[$quarter] = [
                    'opening' => 0,
                    'carryover' => 0,
                    'added' => 0,
                    'current' => 0,
                    'released' => 0,
                    'remarks' =>
                        $rawRemarks,
                ];

                /*
                 * Do NOT change previousCurrent. The next activated
                 * quarter still carries from the latest active quarter.
                 */
                continue;
            }

            /*
             * LEGACY SINGLE QUARTER:
             * rawValue is still the old remaining balance.
             */
            if (
                $item
                && empty($existing)
                && count($quarters) === 1
            ) {
                $opening =
                    $rawValue
                    + $legacyReleased;

                $result[$quarter] = [
                    'opening' =>
                        $opening,

                    'carryover' =>
                        0,

                    'added' =>
                        $opening,

                    'current' =>
                        $rawValue,

                    'released' =>
                        $legacyReleased,

                    'remarks' =>
                        $rawRemarks,
                ];

                $previousCurrent =
                    $rawValue;

                continue;
            }

            /*
             * NEW QUARTER:
             * rawValue is NEW stock for this quarter.
             * Previous quarter remaining is automatically carried
             * forward and is NOT deducted from the historical quarter.
             *
             * Example:
             * Q1 remaining = 10
             * Q2 new stock = 25
             * Q2 opening/current = 35
             * Q1 historical remaining stays 10.
             */
            $carryover =
                max(
                    0,
                    (int) $previousCurrent
                );

            $added =
                $rawValue;

            $opening =
                $carryover
                + $added;

            $result[$quarter] = [
                'opening' =>
                    $opening,

                'carryover' =>
                    $carryover,

                'added' =>
                    $added,

                'current' =>
                    $opening,

                'released' =>
                    0,

                'remarks' =>
                    $rawRemarks,
            ];

            $previousCurrent =
                $opening;
        }

        return $result;
    }

    private function quarterStockCurrentTotal(
        array $quarterStock
    ): int {
        $normalized =
            $this->normalizedStoredQuarterStock(
                $quarterStock
            );

        $latestQuarter =
            $this->latestActiveQuarter(
                $normalized
            );

        if ($latestQuarter === null) {
            return 0;
        }

        return max(
            0,
            (int) (
                $normalized[
                    $latestQuarter
                ]['current']
                ?? 0
            )
        );
    }

    private function quarterStockReleasedTotal(
        array $quarterStock
    ): int {
        return array_sum(
            array_map(
                fn ($entry) =>
                    max(
                        0,
                        (int) (
                            $entry['released']
                            ?? 0
                        )
                    ),
                $quarterStock
            )
        );
    }



    /**
     * Upload or replace the one active reconciliation reference file.
     *
     * This file never updates inventory quantities/assets. It is only
     * read when the Inventory Reconciliation tab is rendered.
     */
    public function uploadReconciliationReference(
        Request $request
    ) {
        $this->authorizeInventoryManagement(
            $request
        );

        $validated = $request->validate([
            'reference_category' =>
                'required|in:supplies,ict,furniture_fixtures,emergency_kits,token_giveaways',

            'reference_file' =>
                'required|file|mimes:xlsx,csv,txt|max:10240',
        ]);

        $file =
            $validated['reference_file'];

        $extension =
            strtolower(
                (string) $file
                    ->getClientOriginalExtension()
            );

        if (!in_array(
            $extension,
            ['xlsx', 'csv', 'txt'],
            true
        )) {
            throw ValidationException::withMessages([
                'reference_file' =>
                    'Please upload an XLSX or CSV file.',
            ]);
        }

        /*
         * Validate that the spreadsheet can be read BEFORE replacing
         * the current reference file.
         */
        try {
            $previewRows =
                $this->parseReconciliationSpreadsheet(
                    $file->getRealPath(),
                    $extension
                );
        } catch (\Throwable $exception) {
            Log::warning(
                'Inventory reconciliation reference parse failed.',
                [
                    'message' =>
                        $exception->getMessage(),
                ]
            );

            $parserMessage =
                trim(
                    (string) $exception->getMessage()
                );

            throw ValidationException::withMessages([
                'reference_file' =>
                    $parserMessage !== ''
                        ? 'Reference file error: ' . $parserMessage
                        : 'The selected reference file could not be read. Please use a valid XLSX or CSV file.',
            ]);
        }

        if (empty($previewRows)) {
            throw ValidationException::withMessages([
                'reference_file' =>
                    'The selected reference file does not contain readable inventory rows.',
            ]);
        }

        $referenceCategory =
            $this->normalizeComparisonCategory(
                $validated['reference_category']
            );

        $directory =
            storage_path(
                'app/inventory/reconciliation/'
                . $referenceCategory
            );

        if (!is_dir($directory)) {
            mkdir(
                $directory,
                0775,
                true
            );
        }

        foreach (
            glob(
                $directory
                . DIRECTORY_SEPARATOR
                . 'reference.*'
            ) ?: []
            as $existingReference
        ) {
            if (
                basename($existingReference)
                !== 'reference.json'
                && is_file($existingReference)
            ) {
                @unlink($existingReference);
            }
        }

        $storedExtension =
            $extension === 'txt'
                ? 'csv'
                : $extension;

        $storedFilename =
            'reference.'
            . $storedExtension;

        $file->move(
            $directory,
            $storedFilename
        );

        $metadata = [
            'reference_category' =>
                $validated['reference_category'],

            'original_name' =>
                $file->getClientOriginalName(),

            'stored_name' =>
                $storedFilename,

            'uploaded_at' =>
                now()->toIso8601String(),

            'uploaded_by' =>
                $request->user()?->name
                ?? $request->user()?->username
                ?? 'Inventory Administrator',

            'row_count' =>
                count($previewRows),
        ];

        file_put_contents(
            $directory
                . DIRECTORY_SEPARATOR
                . 'reference.json',
            json_encode(
                $metadata,
                JSON_PRETTY_PRINT
                | JSON_UNESCAPED_UNICODE
            )
        );

        return back()->with(
            'success',
            $this->inventoryComparisonCategoryLabel(
                $referenceCategory
            )
            . ' reference file saved. Reconciliation results have been refreshed.'
        );
    }

    /**
     * Build all category-scoped Reconciliation results.
     *
     * Each category has its own stored reference file, so uploading
     * an ICT reference never replaces the Supplies reference.
     */
    private function buildInventoryReconciliations(): array
    {
        $results = [];

        foreach (
            [
                'supplies',
                'ict',
                'furniture_fixtures',
                'emergency_kits',
                'token_giveaways',
            ]
            as $category
        ) {
            $results[$category] =
                $this->buildInventoryReconciliation(
                    $category
                );
        }

        return $results;
    }

    /**
     * Build one read-only comparison for one inventory category.
     */
    private function buildInventoryReconciliation(
        string $referenceCategory
    ): array {
        $referenceCategory =
            $this->normalizeComparisonCategory(
                $referenceCategory
            );

        $empty = [
            'has_reference' => false,

            'reference' => [
                'reference_category' =>
                    $referenceCategory,

                'reference_category_label' =>
                    $this->inventoryComparisonCategoryLabel(
                        $referenceCategory
                    ),

                'original_name' => null,
                'uploaded_at' => null,
                'uploaded_by' => null,
                'row_count' => 0,
            ],

            'summary' => [
                'total' => 0,
                'equal' => 0,
                'not_equal' => 0,
                'missing' => 0,
            ],

            'rows' => [],
            'error' => null,
        ];

        $directory =
            storage_path(
                'app/inventory/reconciliation/'
                . $referenceCategory
            );

        if (!is_dir($directory)) {
            return $empty;
        }

        $metadataPath =
            $directory
            . DIRECTORY_SEPARATOR
            . 'reference.json';

        $metadata = [];

        if (is_file($metadataPath)) {
            $decoded =
                json_decode(
                    (string) file_get_contents(
                        $metadataPath
                    ),
                    true
                );

            if (is_array($decoded)) {
                $metadata = $decoded;
            }
        }

        $referencePath = null;
        $extension = null;

        foreach (
            ['xlsx', 'csv']
            as $candidateExtension
        ) {
            $candidate =
                $directory
                . DIRECTORY_SEPARATOR
                . 'reference.'
                . $candidateExtension;

            if (is_file($candidate)) {
                $referencePath =
                    $candidate;

                $extension =
                    $candidateExtension;

                break;
            }
        }

        if (!$referencePath) {
            return $empty;
        }

        try {
            $excelRows =
                $this->parseReconciliationSpreadsheet(
                    $referencePath,
                    (string) $extension
                );

            /*
             * The button that opened Reconciliation already determines
             * the category. Force every spreadsheet row into that scope.
             */
            $excelRows =
                array_values(
                    array_map(
                        function (array $row) use (
                            $referenceCategory
                        ): array {
                            $row['category'] =
                                $referenceCategory;

                            $present =
                                $row['_present']
                                ?? [];

                            if (
                                !in_array(
                                    'category',
                                    $present,
                                    true
                                )
                            ) {
                                $present[] =
                                    'category';
                            }

                            $row['_present'] =
                                $present;

                            return $row;
                        },
                        $excelRows
                    )
                );

            $websiteRows =
                array_values(
                    array_filter(
                        $this->inventoryComparisonRecords(),
                        fn (array $row) =>
                            (
                                $row['category']
                                ?? ''
                            )
                            === $referenceCategory
                    )
                );

            $comparison =
                $this->compareInventoryReference(
                    $excelRows,
                    $websiteRows
                );

            return [
                'has_reference' => true,

                'reference' => [
                    'reference_category' =>
                        $referenceCategory,

                    'reference_category_label' =>
                        $this->inventoryComparisonCategoryLabel(
                            $referenceCategory
                        ),

                    'original_name' =>
                        $metadata['original_name']
                        ?? basename(
                            $referencePath
                        ),

                    'uploaded_at' =>
                        $metadata['uploaded_at']
                        ?? date(
                            DATE_ATOM,
                            filemtime(
                                $referencePath
                            )
                        ),

                    'uploaded_by' =>
                        $metadata['uploaded_by']
                        ?? 'Unknown',

                    'row_count' =>
                        $metadata['row_count']
                        ?? count(
                            $excelRows
                        ),
                ],

                'summary' =>
                    $comparison['summary'],

                'rows' =>
                    $comparison['rows'],

                'error' => null,
            ];
        } catch (\Throwable $exception) {
            Log::error(
                'Inventory reconciliation failed.',
                [
                    'category' =>
                        $referenceCategory,

                    'message' =>
                        $exception->getMessage(),
                ]
            );

            return [
                ...$empty,

                'has_reference' => true,

                'reference' => [
                    'reference_category' =>
                        $referenceCategory,

                    'reference_category_label' =>
                        $this->inventoryComparisonCategoryLabel(
                            $referenceCategory
                        ),

                    'original_name' =>
                        $metadata['original_name']
                        ?? basename(
                            $referencePath
                        ),

                    'uploaded_at' =>
                        $metadata['uploaded_at']
                        ?? null,

                    'uploaded_by' =>
                        $metadata['uploaded_by']
                        ?? 'Unknown',

                    'row_count' =>
                        $metadata['row_count']
                        ?? null,
                ],

                'error' =>
                    'The saved reference file could not be compared. Replace it with a valid XLSX or CSV file.',
            ];
        }
    }

    /**
     * Convert current website inventory into comparison-friendly records.
     *
     * Physical ICT + Furniture/Fixtures are compared per Property Number.
     * Supplies/subscriptions/count-based Other Items are compared per item.
     */
    private function inventoryComparisonRecords(): array
    {
        $records = [];

        $items =
            InventoryItem::query()
                ->orderBy('id')
                ->get();

        foreach ($items as $item) {
            $category =
                strtolower(
                    trim(
                        (string) $item->category
                    )
                );

            $normalizedCategory =
                in_array(
                    $category,
                    ['furniture', 'fixtures'],
                    true
                )
                    ? 'furniture_fixtures'
                    : $category;

            $isPhysicalAsset =
                (
                    $category === 'ict'
                    && !in_array(
                        strtoupper(
                            trim(
                                (string) $item->unit
                            )
                        ),
                        ['MONTH', 'YEAR'],
                        true
                    )
                )
                || in_array(
                    $category,
                    ['furniture', 'fixtures'],
                    true
                );

            $assets =
                is_array($item->ict_assets)
                    ? $item->ict_assets
                    : [];

            if (
                $isPhysicalAsset
                && !empty($assets)
            ) {
                foreach (
                    $assets
                    as $assetIndex => $asset
                ) {
                    if (!is_array($asset)) {
                        continue;
                    }

                    $propertyNumber =
                        trim(
                            (string) (
                                $asset[
                                    'property_number'
                                ]
                                ?? ''
                            )
                        );

                    /*
                     * A physical row without a Property Number cannot be
                     * reliably reconciled against an external sheet.
                     */
                    if ($propertyNumber === '') {
                        continue;
                    }

                    $records[] = [
                        'uid' =>
                            'asset:'
                            . $item->id
                            . ':'
                            . $assetIndex,

                        'kind' => 'asset',

                        'category' =>
                            $normalizedCategory,

                        'category_label' =>
                            $this->inventoryComparisonCategoryLabel(
                                $normalizedCategory
                            ),

                        'item' =>
                            trim(
                                (string) $item->item
                            ),

                        'unit' =>
                            trim(
                                (string) $item->unit
                            ),

                        'inventory_year' =>
                            $item->inventory_year !== null
                                ? (string) $item->inventory_year
                                : '',

                        'available' => '',

                        'description' =>
                            trim(
                                (string) (
                                    $asset['description']
                                    ?? ''
                                )
                            ),

                        'property_number' =>
                            $propertyNumber,

                        'current_user' =>
                            trim(
                                (string) (
                                    $asset['current_user']
                                    ?? ''
                                )
                            ),

                        'location' =>
                            trim(
                                (string) (
                                    $item->location
                                    ?? ''
                                )
                            ),

                        'remarks' =>
                            trim(
                                (string) (
                                    $item->remarks
                                    ?? ''
                                )
                            ),
                    ];
                }

                continue;
            }

            $records[] = [
                'uid' =>
                    'item:'
                    . $item->id,

                'kind' => 'summary',

                'category' =>
                    $normalizedCategory,

                'category_label' =>
                    $this->inventoryComparisonCategoryLabel(
                        $normalizedCategory
                    ),

                'item' =>
                    trim(
                        (string) $item->item
                    ),

                'unit' =>
                    trim(
                        (string) $item->unit
                    ),

                'inventory_year' =>
                    $item->inventory_year !== null
                        ? (string) $item->inventory_year
                        : '',

                'available' =>
                    $item->currently_available !== null
                        ? (string) $item->currently_available
                        : '',

                'description' => '',

                'property_number' => '',

                'current_user' => '',

                'location' =>
                    trim(
                        (string) (
                            $item->location
                            ?? ''
                        )
                    ),

                'remarks' =>
                    trim(
                        (string) (
                            $item->remarks
                            ?? ''
                        )
                    ),
            ];
        }

        return $records;
    }

    private function inventoryComparisonCategoryLabel(
        string $category
    ): string {
        return match ($category) {
            'supplies' =>
                'Supplies',

            'ict' =>
                'ICT',

            'furniture_fixtures' =>
                'Furniture/Fixtures',

            'emergency_kits' =>
                'Emergency Kits',

            'token_giveaways' =>
                'Token and Giveaways',

            default =>
                ucwords(
                    str_replace(
                        '_',
                        ' ',
                        $category
                    )
                ),
        };
    }

    /**
     * Compare spreadsheet rows to website records without changing either.
     */
    private function compareInventoryReference(
        array $excelRows,
        array $websiteRows
    ): array {
        $resultRows = [];
        $matchedWebsiteUids = [];

        foreach (
            $excelRows
            as $index => $excel
        ) {
            if (!is_array($excel)) {
                continue;
            }

            $match =
                $this->findInventoryComparisonMatch(
                    $excel,
                    $websiteRows,
                    $matchedWebsiteUids
                );

            if (
                ($match['state'] ?? null)
                === 'ambiguous'
            ) {
                $resultRows[] = [
                    'id' =>
                        'excel:'
                        . ($index + 1),

                    'status' =>
                        'missing_in_website',

                    'category' =>
                        $excel['category']
                        ?? '',

                    'category_label' =>
                        $this->inventoryComparisonCategoryLabel(
                            $excel['category']
                            ?? ''
                        ),

                    'item' =>
                        $excel['item']
                        ?? '',

                    'property_number' =>
                        $excel['property_number']
                        ?? '',

                    'website' => null,

                    'excel' =>
                        $this->comparisonPublicValues(
                            $excel
                        ),

                    'differences' => [
                        [
                            'field' => 'match',
                            'label' => 'Match',
                            'website' =>
                                'Multiple possible website records',
                            'excel' =>
                                'Needs a more specific key such as Property Number, Unit, Year, or Location',
                        ],
                    ],
                ];

                continue;
            }

            $website =
                $match['record']
                ?? null;

            if (!$website) {
                $resultRows[] = [
                    'id' =>
                        'excel:'
                        . ($index + 1),

                    'status' =>
                        'missing_in_website',

                    'category' =>
                        $excel['category']
                        ?? '',

                    'category_label' =>
                        $this->inventoryComparisonCategoryLabel(
                            $excel['category']
                            ?? ''
                        ),

                    'item' =>
                        $excel['item']
                        ?? '',

                    'property_number' =>
                        $excel['property_number']
                        ?? '',

                    'website' => null,

                    'excel' =>
                        $this->comparisonPublicValues(
                            $excel
                        ),

                    'differences' => [],
                ];

                continue;
            }

            $matchedWebsiteUids[
                $website['uid']
            ] = true;

            $differences =
                $this->inventoryComparisonDifferences(
                    $website,
                    $excel
                );

            $resultRows[] = [
                'id' =>
                    'match:'
                    . $website['uid'],

                'status' =>
                    empty($differences)
                        ? 'equal'
                        : 'not_equal',

                'category' =>
                    $website['category'],

                'category_label' =>
                    $website['category_label'],

                'item' =>
                    $website['item'],

                'property_number' =>
                    $website['property_number'],

                'website' =>
                    $this->comparisonPublicValues(
                        $website
                    ),

                'excel' =>
                    $this->comparisonPublicValues(
                        $excel
                    ),

                'differences' =>
                    $differences,
            ];
        }

        /*
         * Website records not represented by the reference sheet.
         */
        foreach (
            $websiteRows
            as $website
        ) {
            if (
                isset(
                    $matchedWebsiteUids[
                        $website['uid']
                    ]
                )
            ) {
                continue;
            }

            $resultRows[] = [
                'id' =>
                    'website:'
                    . $website['uid'],

                'status' =>
                    'missing_in_excel',

                'category' =>
                    $website['category'],

                'category_label' =>
                    $website['category_label'],

                'item' =>
                    $website['item'],

                'property_number' =>
                    $website['property_number'],

                'website' =>
                    $this->comparisonPublicValues(
                        $website
                    ),

                'excel' => null,

                'differences' => [],
            ];
        }

        usort(
            $resultRows,
            function (
                array $left,
                array $right
            ): int {
                $categoryCompare =
                    strcasecmp(
                        (string) (
                            $left['category_label']
                            ?? ''
                        ),
                        (string) (
                            $right['category_label']
                            ?? ''
                        )
                    );

                if ($categoryCompare !== 0) {
                    return $categoryCompare;
                }

                $itemCompare =
                    strcasecmp(
                        (string) (
                            $left['item']
                            ?? ''
                        ),
                        (string) (
                            $right['item']
                            ?? ''
                        )
                    );

                if ($itemCompare !== 0) {
                    return $itemCompare;
                }

                return strcasecmp(
                    (string) (
                        $left['property_number']
                        ?? ''
                    ),
                    (string) (
                        $right['property_number']
                        ?? ''
                    )
                );
            }
        );

        $summary = [
            'total' =>
                count($resultRows),

            'equal' => 0,

            'not_equal' => 0,

            'missing' => 0,
        ];

        foreach ($resultRows as $row) {
            $status =
                $row['status']
                ?? '';

            if ($status === 'equal') {
                $summary['equal']++;
            } elseif (
                $status === 'not_equal'
            ) {
                $summary['not_equal']++;
            } else {
                $summary['missing']++;
            }
        }

        return [
            'summary' =>
                $summary,

            'rows' =>
                $resultRows,
        ];
    }

    /**
     * Find the most reliable website row for one spreadsheet row.
     */
    private function findInventoryComparisonMatch(
        array $excel,
        array $websiteRows,
        array $alreadyMatched
    ): array {
        $candidates =
            array_values(
                array_filter(
                    $websiteRows,
                    fn (array $row) =>
                        !isset(
                            $alreadyMatched[
                                $row['uid']
                            ]
                        )
                )
            );

        $propertyNumber =
            $this->normalizeComparisonText(
                $excel['property_number']
                ?? ''
            );

        if ($propertyNumber !== '') {
            $propertyMatches =
                array_values(
                    array_filter(
                        $candidates,
                        fn (array $row) =>
                            $this->normalizeComparisonText(
                                $row[
                                    'property_number'
                                ]
                                ?? ''
                            )
                            === $propertyNumber
                    )
                );

            if (count($propertyMatches) === 1) {
                return [
                    'state' => 'matched',
                    'record' =>
                        $propertyMatches[0],
                ];
            }

            if (count($propertyMatches) > 1) {
                return [
                    'state' => 'ambiguous',
                    'record' => null,
                ];
            }

            return [
                'state' => 'missing',
                'record' => null,
            ];
        }

        $item =
            $this->normalizeComparisonText(
                $excel['item']
                ?? ''
            );

        if ($item === '') {
            return [
                'state' => 'missing',
                'record' => null,
            ];
        }

        $candidates =
            array_values(
                array_filter(
                    $candidates,
                    fn (array $row) =>
                        $this->normalizeComparisonText(
                            $row['item']
                            ?? ''
                        )
                        === $item
                )
            );

        $category =
            $this->normalizeComparisonCategory(
                $excel['category']
                ?? ''
            );

        if ($category !== '') {
            $candidates =
                array_values(
                    array_filter(
                        $candidates,
                        fn (array $row) =>
                            (
                                $row['category']
                                ?? ''
                            )
                            === $category
                    )
                );
        }

        foreach (
            [
                'unit',
                'inventory_year',
                'location',
            ]
            as $field
        ) {
            if (
                !in_array(
                    $field,
                    $excel['_present']
                    ?? [],
                    true
                )
            ) {
                continue;
            }

            $value =
                $this->normalizeComparisonText(
                    $excel[$field]
                    ?? ''
                );

            if ($value === '') {
                continue;
            }

            $candidates =
                array_values(
                    array_filter(
                        $candidates,
                        fn (array $row) =>
                            $this->normalizeComparisonText(
                                $row[$field]
                                ?? ''
                            )
                            === $value
                    )
                );
        }

        if (count($candidates) === 1) {
            return [
                'state' => 'matched',
                'record' =>
                    $candidates[0],
            ];
        }

        if (count($candidates) > 1) {
            return [
                'state' => 'ambiguous',
                'record' => null,
            ];
        }

        return [
            'state' => 'missing',
            'record' => null,
        ];
    }

    /**
     * Compare only columns that actually exist in the uploaded spreadsheet.
     */
    private function inventoryComparisonDifferences(
        array $website,
        array $excel
    ): array {
        $differences = [];

        $labels = [
            'category' =>
                'Category',

            'item' =>
                'Item Name',

            'unit' =>
                'Unit of Measure',

            'inventory_year' =>
                'Inventory Year',

            'available' =>
                'Available / Count / Duration',

            'description' =>
                'Description',

            'property_number' =>
                'Property Number',

            'current_user' =>
                'Current User',

            'location' =>
                'Location',

            'remarks' =>
                'Remarks',
        ];

        $present =
            $excel['_present']
            ?? [];

        foreach (
            $labels
            as $field => $label
        ) {
            if (
                !in_array(
                    $field,
                    $present,
                    true
                )
            ) {
                continue;
            }

            $websiteValue =
                $field === 'category'
                    ? $this->normalizeComparisonCategory(
                        $website[$field]
                        ?? ''
                    )
                    : $this->normalizeComparisonValue(
                        $website[$field]
                        ?? '',
                        $field
                    );

            $excelValue =
                $field === 'category'
                    ? $this->normalizeComparisonCategory(
                        $excel[$field]
                        ?? ''
                    )
                    : $this->normalizeComparisonValue(
                        $excel[$field]
                        ?? '',
                        $field
                    );

            if (
                $websiteValue
                === $excelValue
            ) {
                continue;
            }

            $differences[] = [
                'field' =>
                    $field,

                'label' =>
                    $label,

                'website' =>
                    $this->comparisonDisplayValue(
                        $website[$field]
                        ?? '',
                        $field
                    ),

                'excel' =>
                    $this->comparisonDisplayValue(
                        $excel[$field]
                        ?? '',
                        $field
                    ),
            ];
        }

        return $differences;
    }

